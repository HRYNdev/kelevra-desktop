package main

import (
	"log"

	"github.com/HRYNdev/kelevra-desktop/internal/prava"
	"github.com/HRYNdev/kelevra-desktop/internal/vinsluzhba"
)

// Установка службы Windows при обновлении.
//
// Зачем. Служба снимает с человека подтверждение администратора при каждом
// входе в систему и держит туннель, когда окно закрыто. С 0.6.50 она есть, но
// ставится ТОЛЬКО кнопкой «работать без подтверждений» в настройках — и за
// двое суток боевой работы её не нажал никто. Замер 08.09, машина второго
// человека семьи: 0.6.50 стоит, данные переехали в общую папку, а в журнале
// все до одной строки — от процесса окна, ни одной от службы. То есть выпуск
// новой версии сам по себе службу никому не приносит, сколько его ни выпускай.
//
// Решение Вовы 08.09: служба ставится сама при обновлении. Один запрос прав
// при установке всё равно нужен — Windows не регистрирует службу без него, —
// но человек видит его один раз, а не при каждом входе.
//
// Почему именно после обновления, а не при каждом запуске. Обновление это
// единственный момент, когда человек уже согласился что-то менять и смотрит
// на приложение. Просить права на обычном холодном старте значит пугать
// окном администратора того, кто просто включил компьютер.
//
// Отказ не повторяем и ничем не грозим: не поставилась — работаем как
// работали, окном с правами. Следующее обновление предложит снова.
func postavitSluzhbuPosleObnovleniya() {
	est, err := vinsluzhba.Ustanovlena()
	if err != nil {
		// Не Windows или не спросить у диспетчера — не наше дело лезть
		// дальше. Тихо в журнал: на Linux это штатный ответ.
		log.Printf("служба после обновления: не спросить, стоит ли она (%v) — оставляю как есть", err)
		return
	}
	if est {
		return // уже стоит, ничего не спрашиваем
	}
	log.Printf("служба после обновления: не установлена, прошу права и ставлю")
	if err := prava.PoprositDlya(argPostavitSluzhbu); err != nil {
		// Человек отказал в UAC или система не дала — это не беда, а его
		// выбор. Приложение продолжает работать окном.
		log.Printf("служба после обновления не поставлена (%v) — работаю как прежде", err)
		return
	}
	log.Printf("служба после обновления: установка запущена")
}
