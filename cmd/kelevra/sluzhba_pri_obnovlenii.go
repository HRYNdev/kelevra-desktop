package main

import (
	"log"
	"runtime"

	"github.com/HRYNdev/kelevra-desktop/internal/vinsluzhba"
)

// Установка службы Windows при обновлении.
//
// Зачем. С 0.6.77 без службы Kelevra не работает вовсе: неполного режима
// (только браузеры через системный прокси) больше нет, туннель держит служба.
// Тот, кто обновляется со старой версии без службы (сидел в прокси-режиме),
// после обновления получает ту же просьбу прав, что и при первом запуске.
// Решение владельца 08.09 (служба ставится сама при обновлении) и 17.10 («скачал,
// дал права админа, ВСЁ, РАБОТАЕТ»).
//
// Служебное новой версии к этому моменту уже поднято без прав; увидев службу,
// оно уступит ей место само (peredat_mesto.go), а служба поднимет связь
// (sluzhba.PodklyuchitPosleUstanovki).

// nuzhnoStavitSluzhbu — решение, а не исполнение: его держит тест
// (sluzhba_pri_obnovlenii_test.go), потому что живого Windows у нас нет и
// проверить сам вызов нечем.
//
//	os      — система, на которой работаем. Служб Windows больше нигде нет,
//	          и просить там права значит писать в журнал отказ на каждом
//	          обновлении.
//	est     — служба уже установлена.
//	oshibka — не вышло спросить диспетчер служб. Молчим: лезть ставить,
//	          не зная текущего положения, хуже, чем не делать ничего.
func nuzhnoStavitSluzhbu(os string, est bool, oshibka error) bool {
	if os != "windows" {
		return false
	}
	if oshibka != nil {
		return false
	}
	return !est
}

// postavitSluzhbuPosleObnovleniya ставит службу, если её ещё нет.
//
// Отказ не повторяем здесь: окно покажет «Нужны права» с кнопкой «Дать
// права», и следующий запуск руками спросит снова.
func postavitSluzhbuPosleObnovleniya() {
	est, err := vinsluzhba.Ustanovlena()
	if !nuzhnoStavitSluzhbu(runtime.GOOS, est, err) {
		if err != nil {
			log.Printf("служба после обновления: не спросить, стоит ли она (%v) — оставляю как есть", err)
		}
		return
	}
	log.Printf("служба после обновления: не установлена, прошу права и ставлю")
	if err := poprositUstanovkuSluzhby(0); err != nil {
		log.Printf("служба после обновления не поставлена (%v) — окно покажет кнопку «Дать права»", err)
		return
	}
	log.Printf("служба после обновления поставлена")
}
