# -*- coding: utf-8 -*-
"""
Рисует znachok.ico (иконку Windows-сборки Kelevra) по ЕГО канону — вектору
Android-иконки из основного репозитория, а НЕ по устаревшему растру.

Источник чисел (читать, не редактировать):
  /opt/jarvis-goal/repos/prizhilos_repo/kelevra-box/app/src/main/res/drawable/ic_launcher_foreground.xml
  /opt/jarvis-goal/repos/prizhilos_repo/kelevra-box/app/src/main/res/values/ic_launcher_background.xml

Почему это понадобилось (жалоба 28.08): значок взят старый, хотя его уже
  переделали. 25.08 вектор переписали на оливу (#A8CC6B -> #7F9E4A), а
  растровые mipmap-*.png в kelevra-box с 07.08 не перегенерированы и остались БИРЮЗОВЫМИ. Раньше
  znachok.ico был собран из этого устаревшего растра — отсюда бирюза в
  Kelevra.exe. Правка: рисуем заново по вектору, растр больше не используем.

Геометрия (viewport 108x108, как в векторе):
  - фон:                 ПРОЗРАЧНЫЙ вне круга; правка 30.08 (жалоба: значок
                          должен быть круглым, а не квадратом)
                          убрала сплошной КВАДРАТ #111310. Но 30.08 вечером
                          пришла обратная жалоба: значок стал слишком
                          серым — без тёмной
                          подложки под кольцом единственная непрозрачная
                          фигура это обводка толщиной 4 при кадре 72
                          (5.5% ширины), на 16x16 это 0.9px — линия целиком
                          тонет в антиалиасинге и выглядит серой кашей.
                          ПРАВКА 30.08 (вторая): подложка вернулась, но
                          КРУГЛОЙ — залитый круг #111310, центр (54,54),
                          радиус BG_CIRCLE_R=26.5 (в viewport-координатах,
                          до кропа 72) — диск ВНУТРИ кольца, а не под ним.
                          Первый заход рисовал r=30: диск выступал за
                          кольцо, и на 16px на светлой панели иконка
                          читалась чёрной точкой — смотрел глазами.
                          Так иконка и выглядит на телефоне: Android
                          adaptive-icon кладёт круглую маску поверх фона,
                          круг — канон, не выдумка. Требование «не квадрат»
                          соблюдено: внешний контур остаётся кругом (радиус
                          26.5 меньше половины кадра 72/2=36).
  - кольцо:               центр (54,54), радиус 27, strokeWidth 4 — ОДНА и та
                           же на всех размерах .ico (см. «ОДИН рисунок» ниже),
                           обводка линейным градиентом (27,27)->(81,81):
                           #A8CC6B -> #7F9E4A, заливка прозрачная
  - внутреннее свечение:  круг центр (54,54), радиус 19, радиальный градиент
                           от центра #A8CC6B@alpha=0x80 до alpha=0 на радиусе 19,
                           весь слой умножен на fillAlpha=0.16

ОДИН рисунок на все размеры (правка 01.09, отмена хинтинга):
  30.08-31.08 тут жил «хинтинг»: каждый размер .ico рисовался СВОИМ проходом
  с утолщённым кольцом — strokeWidth = max(RING_W, HINT_MIN_STROKE_PX*FRAME/sz),
  и на sz<=32 кольцо ещё и красилось плоским цветом вместо градиента.
  31.08 хинтинг наконец доехал в файл (append_images), порог подняли до 3.0 px,
  и 01.09 итог увидели живьём — жалоба: значок на панели задач, в трее и
    сверху у приложения искривлён, на экране он как минимум дублируется,
    причём два значка разные, и круг у значка стал неоправданно жирным.
  Он прав, и это арифметика, а не вкус. Доля кольца в ширине значка при
  HINT_MIN_STROKE_PX=3: 16px — 18.8%, 24px — 12.5%, 32px — 9.4%, 48px и
  выше — канонические 5.6%. То есть на панели задач и в трее (мелкие кадры)
  значок был втрое жирнее, чем в Проводнике и на крупных, — ТРИ разных
  рисунка под одним именем. Ровно это он и назвал «теперь разные».
  Поэтому хинтинга больше нет. Значок рисуется РОВНО ОДИН раз (draw_canvas
  при суперсэмплинге SS), кадрируется один раз, и каждый размер .ico —
  честное LANCZOS-уменьшение ЭТОГО ЖЕ кадра. Толщина кольца во всех
  размерах одна и та же доля ширины: RING_W/FRAME = 4/72 = 5.56%.
  Тот же вектор, теми же числами, рисует и кольцо в шапке окна
  (internal/sluzhba/oblik/index.html) — там оно вообще убрано как дубль
  значка окна, см. комментарий в шапке.
  Если мелкий кадр когда-нибудь снова покажется серым — лечить это надо
  подложкой/цветом (BG_CIRCLE_R, RING_START), одинаковыми на всех размерах,
  а НЕ толщиной, разной на каждом: разная толщина это разный значок.

  Побочно правка ПОЧИНИЛА крупные кадры, и это стоит знать, чтобы не принять
  за регрессию. Прежний render_size уменьшал холст до 108, кадрировал до 72 —
  и дальше РАСТЯГИВАЛ эти 72 точки до 128 и 256. То есть самый заметный кадр
  значка был увеличенной картинкой 72x72: мягкой не от градиента, а от
  интерполяции. Замер 01.09 против канона, отрисованного сразу в 256:
  старый кадр расходился с ним в среднем на 8.14/255 (максимум по каналу 255),
  новый — на 0.00/255, знак в знак. Число «цветов» в 256-м кадре при этом
  упало 6858 -> 1885: пропали не оттенки градиента, а тысячи цветов, которые
  выдумала интерполяция при растяжении. Градиент тот же самый, кольцо просто
  перестало быть размытым.

Кадр (72 из 108):
  Android adaptive-icon обрезает foreground до центральных ~2/3 (эквивалент
  центрального квадрата 72x72 из 108x108 viewport) — так кольцо и было видно
  на телефоне. У Windows .ico маски adaptive-icon нет, поэтому чтобы кадр
  (какую долю ширины занимает кольцо) не поменялся при замене бирюзы на
  оливу, здесь тоже берём центральный квадрат 72x72 из холста 108x108 и его
  масштабируем на все размеры .ico. Это НЕ произвольное решение — это тот же
  кроп, что уже был у бирюзовой иконки (проверено щупом palette_probe).

Рисуется с суперсэмплингом 8x (в 864x864) и уменьшается LANCZOS'ом, чтобы
антиалиасинг кольца был гладким на маленьких размерах .ico.
"""
import os
from PIL import Image, ImageDraw

VIEWPORT = 108
FRAME = 72  # центральный кроп 72 из 108 (2/3), как у adaptive-icon
SS = 8  # суперсэмплинг

BG_FILL = (0x11, 0x13, 0x10, 0xFF)  # #111310, круглая подложка (см. докстринг)
BG_CIRCLE_R = 26.5  # радиус круглой подложки: МЕНЬШЕ внешнего края кольца (27+w/2),
                    # чтобы контур фигуры давала олива, а не тёмный диск. При r=30 подложка
                    # выступала за кольцо и на 16px иконка читалась чёрной точкой (30.08, глаза).
RING_START = (0xA8, 0xCC, 0x6B)  # #A8CC6B, у (27,27) на viewport
RING_END = (0x7F, 0x9E, 0x4A)    # #7F9E4A, у (81,81) на viewport
GLOW_COLOR = (0xA8, 0xCC, 0x6B)  # #A8CC6B
GLOW_FILL_ALPHA = 0.16
GLOW_CENTER_ALPHA = 0x80

CX, CY = 54.0, 54.0
RING_R = 27.0
RING_W = 4.0
GLOW_R = 19.0
OUT_ICO = os.path.join(os.path.dirname(__file__), "znachok.ico")
# Размеры, в которых Windows реально показывает значок: 16 — заголовок окна,
# Alt-Tab и мелкий список Проводника; 20/24 — панель задач и трей на 100-125%
# масштаба; 32/40 — панель задач на 150-200% и «средние значки»; 48 — крупные
# значки Проводника; 64/128/256 — «огромные» и превью. Раньше 20 и 40 в файле
# не было вовсе, и эти два кадра Windows ужимала сама из 24/48 своим быстрым
# фильтром — ещё один способ увидеть на экране «разные» значки.
ICO_SIZES = [16, 20, 24, 32, 40, 48, 64, 128, 256]


def lerp(a, b, t):
    return a + (b - a) * t


def ring_color_at(px, py, s):
    """Цвет линейного градиента (27,27)->(81,81) в точке (px,py) в масштабе s."""
    x0, y0 = 27 * s, 27 * s
    x1, y1 = 81 * s, 81 * s
    dx, dy = x1 - x0, y1 - y0
    denom = dx * dx + dy * dy
    t = ((px - x0) * dx + (py - y0) * dy) / denom
    t = max(0.0, min(1.0, t))
    r = lerp(RING_START[0], RING_END[0], t)
    g = lerp(RING_START[1], RING_END[1], t)
    b = lerp(RING_START[2], RING_END[2], t)
    return (r, g, b)


def draw_canvas(s):
    """Рисует холст VIEWPORT*s x VIEWPORT*s (RGBA) — весь значок целиком.

    Параметров, зависящих от итогового размера .ico, у неё БОЛЬШЕ НЕТ
    (были ring_w и flat — хинтинг, отменённый 01.09, см. докстринг модуля):
    рисунок один, размеры получаются из него уменьшением.
    """
    size = int(VIEWPORT * s)
    base = Image.new("RGBA", (size, size), (0, 0, 0, 0))

    # --- круглая подложка #111310 (канон adaptive-icon; НЕ квадрат)
    bgc = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    bpx = bgc.load()
    br = BG_CIRCLE_R * s
    bcx, bcy = CX * s, CY * s
    x0 = max(0, int(bcx - br) - 2)
    x1 = min(size, int(bcx + br) + 2)
    y0 = max(0, int(bcy - br) - 2)
    y1 = min(size, int(bcy + br) + 2)
    for y in range(y0, y1):
        for x in range(x0, x1):
            d = ((x + 0.5 - bcx) ** 2 + (y + 0.5 - bcy) ** 2) ** 0.5
            if d <= br:
                bpx[x, y] = BG_FILL
    base = Image.alpha_composite(base, bgc)

    # --- внутреннее свечение: радиальный градиент, умноженный на fillAlpha 0.16
    glow = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    gpx = glow.load()
    gr = GLOW_R * s
    gcx, gcy = CX * s, CY * s
    x0 = max(0, int(gcx - gr) - 2)
    x1 = min(size, int(gcx + gr) + 2)
    y0 = max(0, int(gcy - gr) - 2)
    y1 = min(size, int(gcy + gr) + 2)
    for y in range(y0, y1):
        for x in range(x0, x1):
            d = ((x + 0.5 - gcx) ** 2 + (y + 0.5 - gcy) ** 2) ** 0.5
            if d > gr:
                continue
            t = d / gr
            a = lerp(GLOW_CENTER_ALPHA, 0, t) * GLOW_FILL_ALPHA
            gpx[x, y] = (GLOW_COLOR[0], GLOW_COLOR[1], GLOW_COLOR[2], int(round(a)))
    base = Image.alpha_composite(base, glow)

    # --- кольцо: заливка прозрачная, только обводка шириной RING_W градиентом
    ring = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    rpx = ring.load()
    r_out = (RING_R + RING_W / 2) * s
    r_in = (RING_R - RING_W / 2) * s
    rcx, rcy = CX * s, CY * s
    x0 = max(0, int(rcx - r_out) - 2)
    x1 = min(size, int(rcx + r_out) + 2)
    y0 = max(0, int(rcy - r_out) - 2)
    y1 = min(size, int(rcy + r_out) + 2)
    for y in range(y0, y1):
        for x in range(x0, x1):
            px, py = x + 0.5, y + 0.5
            d = ((px - rcx) ** 2 + (py - rcy) ** 2) ** 0.5
            if r_in <= d <= r_out:
                col = ring_color_at(px, py, s)
                rpx[x, y] = (int(round(col[0])), int(round(col[1])), int(round(col[2])), 255)
    base = Image.alpha_composite(base, ring)
    return base


def kadr_kanona():
    """Тот САМЫЙ рисунок — один на все размеры значка.

    Холст рисуется при суперсэмплинге SS (864x864) и кадрируется центральным
    квадратом FRAME из VIEWPORT прямо в этом масштабе: так уменьшение до
    каждого размера .ico идёт ОДНИМ LANCZOS-проходом от самого точного
    исходника, а не двумя подряд (сначала до 72, потом до 16).
    """
    big = draw_canvas(SS)
    otstup = int(round((VIEWPORT - FRAME) / 2 * SS))
    storona = int(round(FRAME * SS))
    return big.crop((otstup, otstup, otstup + storona, otstup + storona))


def render_size(sz, kanon=None):
    """Один размер значка — честное уменьшение ОБЩЕГО кадра kadr_kanona().

    kanon передаётся, чтобы build() нарисовал холст один раз на все размеры,
    а не по разу на каждый: это не только быстрее, это ещё и доказательство
    «рисунок ровно один» самой формой кода — подсунуть сюда другой рисунок
    для другого размера уже негде.
    """
    if kanon is None:
        kanon = kadr_kanona()
    return kanon.resize((sz, sz), Image.LANCZOS)


def build():
    kanon = kadr_kanona()
    imgs = [render_size(sz, kanon) for sz in ICO_SIZES]

    # append_images остаётся и после отмены хинтинга. Без него PIL ужимает под
    # каждый размер ОДИН переданный образ (256-й) своим фильтром, то есть
    # мелкие кадры получаются двойным уменьшением 864 -> 256 -> 16, а не
    # честным одинарным 864 -> 16: на 16px это видимая разница в чистоте
    # кольца. С append_images в файл ложатся ровно те кадры, что посчитал
    # render_size от общего kadr_kanona(). Стенд: stend/znachok_odin.py.
    largest = imgs[-1]
    largest.save(
        OUT_ICO,
        format="ICO",
        sizes=[(i.width, i.height) for i in imgs],
        append_images=imgs[:-1],
    )
    return imgs


if __name__ == "__main__":
    imgs = build()
    print("написано:", OUT_ICO, "образов:", len(imgs), "размеры:", [i.size for i in imgs])
