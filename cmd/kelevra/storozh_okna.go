package main

import (
	"log"
	"time"

	"github.com/HRYNdev/kelevra-desktop/internal/kopiya"
)

// Беда 21.08, словами человека: «у меня 2 приложения кельевра открыто».
//
// Окно и служба — разные процессы (см. main.go). Служба умеет уйти сама:
// «Полная защита» перезапускает .exe с правами администратора, а старая
// служба гасит своё ядро и выходит; «Выход» из значка в трее делает то же.
// А окно про это не узнаёт НИКОГДА: команды закрыться ему никто не шлёт,
// его страница уже загружена в память, и запросы к мёртвому адресу в
// index.html глотает `catch (e) { return; }`. Снаружи это выглядит живым
// окном — человек закрывает его крестиком руками и видит вторую копию.
//
// Лечим не частный случай с правами, а сам разрыв: окно без своей службы
// показывать нечего, поэтому оно закрывается само.

const (
	// shagStorozha — как часто щупаем свою службу. Реже, чем опрос состояния
	// в окне: это не показания, а вопрос жизни и смерти.
	shagStorozha = 2 * time.Second
	// molchaniyDoZakrytiya — сколько подряд промахов терпим. Один промах —
	// это не смерть: служба могла быть занята, а на слабой машине запрос и
	// вовсе не успел за таймаут. Три подряд (≈6 с) — это уже не занятость.
	molchaniyDoZakrytiya = 3
	// srokOzhidaniyaZameny — сколько ждём службу, поднявшуюся ВЗАМЕН.
	//
	// Замолчавшая служба и умершая служба выглядят одинаково, а разница для
	// человека огромная: в первом случае окно должно дождаться и открыться
	// заново, во втором — закрыться. Раньше выбор делался ОДНИМ взглядом на
	// метку на шестой секунде — и всегда попадал мимо: диспетчер служб
	// поднимает упавшую службу через 5 секунд, а метку новый процесс пишет
	// ещё позже (замер 08.09: возвращение занимало 5-11 секунд). Метка в тот
	// миг держит адрес мёртвой копии, kopiya.Nayti честно отвечает «никого»,
	// и окно уходило по ветке «закрываю насовсем».
	//
	// Минута покрывает первую попытку диспетчера (5 с) и вторую (15 с) с
	// запасом на медленный диск. Дольше держать окно бессмысленно: если за
	// минуту служба не вернулась, это отказ, а не перезапуск.
	srokOzhidaniyaZameny = 60 * time.Second
)

// storozhitSluzhbu закрывает окно, когда служба, ради которой оно открыто,
// перестала отвечать. zakryt зовётся ровно один раз и только по этой причине.
// Отказ безопасный: пока служба отвечает — окно не трогаем вообще.
//
// Перед закрытием смотрим, не поднялась ли служба ЗАНОВО по другому адресу.
//
// Замер 08.09 с живой машины. Человек нажал «Обновить», служба поставила
// новую версию, ушла с отказом, диспетчер поднял её за пять секунд — но с
// НОВЫМ случайным портом (было 61680, стало 54520). Окно держало старый
// адрес, стучалось в мёртвый порт и осталось с надписью «Kelevra
// перезапускается…» навсегда. Само обновление при этом прошло полностью.
//
// Поэтому молчание — ещё не приговор: сперва спрашиваем метку на диске
// (kopiya.Nayti), и если там живой адрес и он ДРУГОЙ, окно надо не хоронить,
// а открыть заново на нём.
//
// perezapustit — вопрос «служба вернулась НОВЕЕ этого окна?» (17.10). Зовётся
// после каждого возвращения службы: переезд на новый адрес, ожила на прежнем,
// ответила после одиночного промаха. true — окно уходит на перезапуск само
// (perezapustit его уже начал), сторожу тут больше делать нечего. nil — не
// спрашивать (тесты старых веток).
//
// Зачем. Обновление под службой Windows меняет только службу: окно — процесс
// старой версии — переходило на новый адрес и жило дальше со страницей новой
// версии, но со старыми привязками Go. 17.10 так «Панель сети» в окне 0.6.73
// ушла в системный браузер: kelevraPanel у старого процесса нет.
func storozhitSluzhbu(url, papka string, shag time.Duration, predel int, srokZameny time.Duration, zakryt func(), perejti func(string), perezapustit func(string) bool) {
	novee := func(adres string) bool { return perezapustit != nil && perezapustit(adres) }
	promahov := 0
	for {
		time.Sleep(shag)
		if kopiya.Otvechaet(url) {
			// Ответ после промаха — служба могла успеть перезапуститься на
			// том же порту быстрее, чем сторож разуверился.
			if promahov > 0 && novee(url) {
				return
			}
			promahov = 0
			continue
		}
		promahov++
		if promahov < predel {
			log.Printf("сторож окна: служба не ответила (%d из %d)", promahov, predel)
			continue
		}
		// Служба молчит. Это ещё не приговор: ровно так выглядит и её
		// перезапуск после обновления. Ждём замену, а не хороним с первого
		// взгляда (см. srokOzhidaniyaZameny).
		log.Printf("сторож окна: служба молчит %d проверки подряд, жду замену до %s", predel, srokZameny)
		if adres, vernulas := zhdatZamenu(url, papka, shag, srokZameny); adres != "" {
			// ОКНО НЕ ЗАКРЫВАЕМ, А ПЕРЕВОДИМ НА НОВЫЙ АДРЕС.
			//
			// Раньше здесь окно закрывалось, а main открывал новое. Проверка
			// на живом стенде 09.09 показала, чем это кончается: второе окно
			// в том же процессе создать нельзя — go-webview2 падает внутри
			// себя (nil pointer в edge.Chromium.Init), ещё до возврата, так
			// что никакая проверка «окно не создалось» не спасает. Человек
			// получал белое окно и сообщение об аварии — ту же беду с другого
			// конца.
			//
			// А закрывать и незачем: окно живое, поменялся только адрес
			// службы. Переход на него дешевле, быстрее и без единого нового
			// окна на экране.
			if novee(adres) {
				return
			}
			log.Printf("сторож окна: служба переехала на %s (была %s) — перевожу окно на новый адрес", adres, url)
			perejti(adres)
			url = adres
			promahov = 0
			continue
		} else if vernulas {
			if novee(url) {
				return
			}
			log.Printf("сторож окна: служба ответила по прежнему адресу, продолжаю дозор")
			promahov = 0
			continue
		}
		log.Printf("сторож окна: замены нет за %s, закрываю окно", srokZameny)
		zakryt()
		return
	}
}

// zhdatZamenu ждёт, пока служба вернётся — на прежнем адресе или на новом.
//
// Отдаёт: адрес новой службы (если переехала) и признак «ожила на прежнем».
// Пусто и false — за отведённый срок не вернулась никак.
//
// Почему смотрим ОБА исхода. Диспетчер служб поднимает упавшую службу заново,
// и порт она берёт случайный (net.Listen на :0) — обычно новый, но может
// достаться и прежний. В первом случае окно надо открыть заново на новом
// адресе, во втором — просто продолжить работу, ничего не закрывая.
func zhdatZamenu(url, papka string, shag, srok time.Duration) (string, bool) {
	konec := time.Now().Add(srok)
	for time.Now().Before(konec) {
		time.Sleep(shag)
		if kopiya.Otvechaet(url) {
			return "", true
		}
		if adres, est := kopiya.Nayti(papka); est && adres != url {
			return adres, false
		}
	}
	return "", false
}
