// argSluzhba/argTiho — режимы запуска этого же .exe (см. шапку файла).
// argSmena — не режим, а сообщение от прошлой, ещё не повышенной копии:
// значение после флага — её pid (см. prava.Poprosit и polnayaZashchita).
// argPriStarte — сообщение той же природы, что и argSmena: новая, уже
// повышенная копия узнаёт из него, что смена вызвана запросом прав СРАЗУ ПРИ
// СТАРТЕ (sprositPravaNaStarte), а не кнопкой «Включить для всех программ»
// (polnayaZashchita). Разница важна ровно в одном месте — vosstanovitPolnuyuZashchitu
// не должна сама дёргать /api/podklyuchit: человек только открыл программу и
// ничего подключать не просил.
const (
	argSluzhba   = "--sluzhba"
	argTiho      = "--tiho"
	argSmena     = "--smena"
	argPriStarte = "--pri-starte"
)

// srokOzhidaniyaSmeny — сколько новая, уже повышенная копия ждёт смерти
// старой перед тем, как всё равно занять её место. Гонка 25.08 (при смене
// режима на секунды открывалось два окна) была устроена ровно наоборот —
// фиксированным time.Sleep(300ms) на СТОРОНЕ СТАРОЙ копии без всякой
// обратной связи; здесь ждёт та копия, что реально должна знать правду,
// и явным опросом, а не наугад.
const srokOzhidaniyaSmeny = 10 * time.Second

// srokPodnyatiyaSluzhby — сколько окно ждёт, пока отдельно запущенная служба
// отметится меткой копии. Дольше держать человека перед пустым экраном
// бессмысленно: если за 20 секунд служба не встала, дело не в медленном
// диске, а в реальном отказе (см. umeret ниже).
const srokPodnyatiyaSluzhby = 20 * time.Second

func main() {
	papka := hranenie.Papka()
	putZhurnala, zakryt := otkrytZhurnal(papka)
	defer zakryt()

	// Окно и служба — теперь РАЗНЫЕ процессы одного .exe (беда 20.08: окно и
	// служба жили в одном процессе, и крестик на окне гасил ядро с прокси
	// молча). Прокси ставит и снимает только служба, поэтому только она имеет
	// право звать proksi.Snyat() из lovitPaniku — окну чужой прокси не трогать.
	// Исключение — snyatOsirotevshiySled ниже: это не «окно гасит прокси
	// живой службы», а уборка за службой, которая уже доказанно мертва
	// (без этого исключения жёсткая смерть процесса, которую не ловит ни
	// один сигнал, оставляла бы прокси висеть навсегда — см. её комментарий).
	//
	// KELEVRA_BEZ_OKNA=1 — синоним --sluzhba: на нём стоит мой стенд
	// (stend/windows.sh) и разбор беды у человека, менять эту переменную нельзя.
	rezhimSluzhby := os.Getenv("KELEVRA_BEZ_OKNA") == "1" || estArg(argSluzhba)
	defer lovitPaniku(putZhurnala, rezhimSluzhby)
	log.Printf("--- запуск Kelevra %s (%s/%s), данные: %s", podpiska.Versiya, runtime.GOOS, runtime.GOARCH, papka)

	// Осиротевший след туннеля разбираем НА СТАРТЕ ЛЮБОЙ копии — до служебной
	// ветки ниже, до окна и задолго до первого подключения.
	//
	// Замер 31.08 на стенде: подняли туннель, сняли питание. После загрузки
	// адаптера нет, маршруты чистые — а tunnel.json остался лежать и
	// СЛЕДУЮЩИМ запуском убран не был, просто перезаписался новым pid при
	// следующем подключении. Причина ровно в этом месте: уборка стояла ниже
	// ветки rezhimSluzhby, то есть в процессе ОКНА, а туннель поднимает и след
	// пишет процесс СЛУЖБЫ (--sluzhba / KELEVRA_BEZ_OKNA=1, им же живёт стенд
	// и им же приложение висит в трее). Служба до уборки не доходила никогда.
	//
	// Уборка идемпотентна и от двойного вызова не портится: окно приберёт
	// след, поднятая им следом служба не найдёт уже ничего и промолчит.
	// Живая чужая копия защищена внутри — её след не трогаем (см. tunnel.UbratOsirotevshiy).
	snyatOsirotevshiySledTunnelya(papka)

	// Нас запустил диспетчер служб Windows — это отдельный режим, и узнаётся
	// он у системы, а не по аргументу: аргумент подставляет она сама, но при
	// ручном запуске с тем же аргументом службы вокруг нас нет, и svc.Run
	// повис бы, не дождавшись диспетчера.
	//
	// Стоит ВЫШЕ обычной служебной ветки и сразу после уборки следа туннеля:
	// уборка нужна и здесь (после жёсткого выключения компьютера служба
	// поднимется первой и до окна), а вот всё оконное ниже — уже нет.
	if vinsluzhba.PodSluzhboy() {
		log.Printf("запущены диспетчером служб Windows")
		if err := vinsluzhba.Krutit(func(ctx context.Context) {
			rabotaSluzhbyWindows(ctx, papka, putZhurnala)
		}); err != nil {
			log.Printf("служба Windows не встала: %v", err)
		}
		return
	}

	if rezhimSluzhby {
		zapustitSluzhbu(papka, putZhurnala)
		return
	}

	// Жёсткая смерть предыдущего запуска (Диспетчер задач, выключение или
	// перезагрузка Windows, пропадание питания) не даёт службе дойти до
	// proksi.Snyat() в конце zapustitSluzhbu — реестр остаётся с нашим прокси
	// висеть без ядра за ним, и у человека НЕ грузится ни один сайт, пока он
	// сам не откроет Kelevra и не выйдет аккуратно.
	snyatOsirotevshiySled(papka)
	// То же самое для туннеля (вывод у проверки другой: там снимать нечего,
	// там надо УБЕДИТЬСЯ, что после жёсткой смерти ничего не осталось) стоит
	// ВЫШЕ, до ветки служебного режима — см. snyatOsirotevshiySledTunnelya и
	// комментарий у самого вызова.

	// Свежесть больше не подменяет .exe САМА на холодном старте (заказ 26.08:
	// обновление приходит само, а ставит его человек нажатием, а не автомат —
	// раньше здесь стоял obnovitsya(), который качал и ставил новую сборку
	// молча, без единого клика, и человек это «автоматом» не видел никогда:
	// копия успевала стать свежей раньше, чем он моргал). Находка и предложение
	// — теперь дело службы сразу после подъёма (internal/sluzhba.
	// SleditZaObnovleniem: первая проверка не ждёт периода), установка —
	// только по тычку человека в пузырь трея (PostavitNaydennoe). Здесь
	// остаётся только уборка ХВОСТА прошлого обновления.
	ubratHvostProshlogoObnovleniya()

	// --smena <pid> — эта копия только что повышена через UAC из
	// polnayaZashchita: старая копия (тот самый pid) ещё может быть жива и
	// держит метку. adresKopii ждёт её смерти сама, а не идёт по обычной
	// ветке «нашёл чужую живую копию» (см. её комментарий).
	smenaPID, _ := argSmenaPID()

	tiho := tihiyZapusk(os.Args)
	priStarte := priStarteZapusk(os.Args)

	// Заказ 29.08: подтверждение прав должно вылезать при старте программы и
	// больше не мешать — окно UAC теперь спрашивается сразу тут,
	// ДО adresKopii (иначе уже открытое окно мигнуло бы поверх запроса прав).
	// nuzhnoSprositPravaNaStarte и её комментарий держат все условия разом.
	// estChuzhayaKopiya считаем, только когда остальные условия уже пройдены:
	// kopiya.Nayti при мёртвой метке ждёт ответа до kopiya.Skolko, и платить
	// эту цену на КАЖДОМ обычном запуске (когда права и так уже есть) незачем.
	estPrava := prava.Est()
	estChuzhayaKopiya := false
	if !estPrava && !tiho && smenaPID == 0 {
		_, estChuzhayaKopiya = kopiya.Nayti(papka)
	}
	if nuzhnoSprositPravaNaStarte(estPrava, tiho, smenaPID, estChuzhayaKopiya) {
		if sprositPravaNaStarte(papka) {
			return
		}
	}

	// Окно — ВНЕ замка (см. adresKopii): pokazatOkno не возвращается, пока
	// человек не закроет окно.
	adres, chuzhaya, itogOkna := adresKopii(papka, putZhurnala, smenaPID)
	if smenaPID > 0 {
		// Второй заход уборки — и он-то и убирает хвост по-настоящему. Первый
		// (ubratHvostProshlogoObnovleniya выше по main) звучит ещё ДО zhdatSmenu,
		// когда старая копия жива и держит свой файл: Windows не даёт удалить
		// запущенный .exe, os.Remove тихо отказывает, и <имя>.old остаётся
		// лежать на виду рядом с приложением до следующего запуска руками —
		// ровно то, что человек и видел 02.09 («появляется .old, и всё»).
		// Здесь старая копия уже подтверждённо мертва (zhdatSmenu внутри
		// adresKopii), файл свободен, откатываться больше некуда и незачем:
		// новая версия работает.
		ubratHvostPosleSmeny()
	}
	// Смена прав по кнопке «Включить для всех программ» (--smena БЕЗ --tiho и
	// БЕЗ --pri-starte) обязана не просто перезапустить приложение, а довести
	// до конца то, ради чего её позвали: человек просил защиту, а не рестарт
	// (см. vosstanovitPolnuyuZashchitu). Автообновление (--tiho --smena) и
	// запрос прав при старте (--smena --pri-starte, sprositPravaNaStarte) сюда
	// не попадают — ни то, ни другое не значит «человек нажал Подключить».
	if smenaPID > 0 && !tiho && !priStarte {
		vosstanovitPolnuyuZashchitu(adres)
	}
	// pokazatLiOkno, а не голое !tiho: смена после обновления приходит с --tiho
	// (obnovlenie.go: zapustitSmenuPosleObnovleniya), и до 02.09 этого хватало,
	// чтобы человек, нажавший «Обновить» в открытом окне, остался вовсе без
	// окна — вся жалоба 02.09 целиком (разбор в шапке smena_okna.go).
	if pokazatLiOkno(tiho, smenaPID, itogOkna) {
		// Беда 23.08: adresKopii уже отличает «нашёл чужую копию» от «поднял
		// свою службу», но раньше main звал pokazatOkno одинаково в обоих
		// случаях — второе окно создавалось поверх уже открытого первого, оба
		// опрашивали /api/sostoyanie независимо, и второе слало podklyuchit
		// на уже работающее ядро (та самая ошибка Zapustit, см. yadro.go).
		// Если копия чужая, сперва пробуем поднять уже существующее окно —
		// и только если его не нашли (не успело появиться), откатываемся на
		// старое поведение и создаём своё.
		if chuzhaya {
			log.Printf("адрес взят у чужой копии, пробую поднять её окно вместо создания своего")
			// Человек кликнул значок в трее — живая копия могла висеть там
			// неделями, и её собственная периодическая проверка
			// (internal/sluzhba.SleditZaObnovleniem) ещё нескоро дойдёт до
			// своего тика. Открытие окна — момент не хуже холодного старта,
			// чтобы спросить: толкаем чужую копию проверить, но не ждём её
			// ответа — это не наше дело здесь и не имеет права задержать
			// открытие окна.
			podtolknutFonovuyuProverku(adres)
			if podnyatChuzheeOkno() {
				return
			}
			log.Printf("чужое окно не нашлось, открываю своё")
		}
		pokazatOkno(adres)
	}
}

// adresKopii отвечает на единственный вопрос запуска: по какому адресу живёт
// ядро — уже поднятое кем-то или поднятое нами прямо сейчас. Не возвращается,
// пока ответа нет: если своя служба не встала, зовёт umeret. Второе
// возвращаемое значение — адрес взят у ЧУЖОЙ копии (kopiya.Nayti), а не
// поднят нами только что: вызывающему это нужно, чтобы решить, пробовать ли
// поднять чужое уже открытое окно вместо создания своего (см. main()).
// Третье — что смена застала на экране (itogSmenyOkna): было ли у прошлой
// копии открытое окно и ушло ли оно. По нему main решает, вернуть ли человеку
// окно взамен закрытого (pokazatLiOkno). Вне смены оно нулевое: закрывать было
// нечего, а значит и возвращать нечего.
//
// Всё решение целиком — под замком ОС. Беда 23.08: Диспетчер задач показывал
// по несколько Kelevra.exe сразу («(3)» и «(9)»), и отключение с двумя
// открытыми окнами падало ошибкой. Nayti() читает файл-метку, а служба
// записывает её не мгновенно: между стартом первой службы и появлением метки
// есть окно длиной в подъём службы. Два .exe, запущенных подряд, оба проходят
// Nayti() с ответом «копии нет» и оба поднимают своё ядро на одни порты —
// stend/dvoynoy_zapusk.sh ловил это 5 раз из 5, с замком 0 из 5. Файл не
// умеет быть атомарным сам с собой между двумя процессами, замок ОС умеет.
//
// Замок живёт ровно в этой функции, и это главное в её существовании: окно
// показывает уже вызывающий, снаружи. Держи мы замок до конца процесса —
// починка гонки стоила бы штатного сценария «щёлкнул по значку, пока
// приложение работает»: второй .exe висел бы на чужом замке все 20 секунд,
// ещё не дойдя до чтения метки, и человек видел бы, что ничего не
// происходит. Под wine это не проверить (окна нет), поэтому запрет держится
// не стендом, а формой: pokazatOkno вызвать отсюда попросту нельзя.
func adresKopii(papka, putZhurnala string, smenaPID int) (string, bool, itogSmenyOkna) {
	// Срок ожидания тот же, что окно и так готово ждать службу: дольше держать
	// человека всё равно нечем. Не взяли (истёк срок или примитив недоступен) —
	// идём по старой схеме: это прежнее поведение, а не новый отказ.
	zamok, estZamok := kopiya.Vzyat(srokPodnyatiyaSluzhby)
	if !estZamok {
		log.Printf("замок запуска не взят за %s (держит другой запуск или примитив недоступен), продолжаю без него", srokPodnyatiyaSluzhby)
	}
	defer zamok.Otdat()

	var itogOkna itogSmenyOkna
	if smenaPID > 0 {
		// Смена режима (см. polnayaZashchita): старая копия жива и держит
		// метку нарочно. Ждём её смерти вместо того, чтобы, как обычная
		// вторая копия, открыть её (умирающее) окно.
		zhdatSmenu(smenaPID)
		kopiya.Osvobodit(papka)
		// Окно старой копии — ОТДЕЛЬНЫЙ процесс (не smenaPID, это pid
		// службы): о смерти своей службы оно узнаёт только от собственного
		// сторожа (storozh_okna.go), а тот терпит 3 промаха по 2с (≈6с) —
		// нарочно медленно, чтобы не закрыть окно на разовую заминку живой
		// службы. Не закрой мы его сами прямо сейчас — на эти секунды на
		// экране будет два окна разом: мёртвое старое (ещё не дождалось
		// своего сторожа) и новое, которое вот-вот откроет эта копия. Старая
		// служба уже подтверждённо мертва (zhdatSmenu выше), поэтому её окно
		// закрыть безопасно прямо сейчас, не дожидаясь чужого таймаута.
		//
		// Итог этого закрытия — не побочная мелочь, а замер, по которому main
		// узнаёт, ждёт ли человек окна взамен: другого источника этой правды
		// у новой копии нет (см. шапку smena_okna.go).
		itogOkna = zakrytStaroeOkno()
	} else if adres, est := kopiya.Nayti(papka); est {
		// Приложение уже работает: открываем его окно, а не поднимаем второе
		// ядро на те же порты. Для человека двойной запуск выглядит как
		// «показать окно».
		log.Printf("копия уже запущена, открываю её окно: %s", adres)
		return adres, true, itogOkna
	}

	// Службы ещё нет: поднимаем её ОТДЕЛЬНЫМ отсоединённым процессом и ждём
	// метку копии. Раньше это же место поднимало службу прямо тут, в процессе
	// окна, — и служба умирала вместе с окном.
	adres, err := podnyatSluzhbuOtdelno(papka)
	if err != nil {
		umeret(putZhurnala, "служба Kelevra не поднялась за 20 секунд", err)
	}
	return adres, false, itogOkna
}

// argSmenaPID ищет "--smena <pid>" среди аргументов запуска (см. константы
// вверху файла). Это не режим самого запуска, а сообщение от прошлой,
// ещё не повышенной копии, которая только что позвала ShellExecuteW.
func argSmenaPID() (int, bool) {
	for i, a := range os.Args {
		if a == argSmena && i+1 < len(os.Args) {
			if pid, err := strconv.Atoi(os.Args[i+1]); err == nil && pid > 0 {
				return pid, true
			}
		}
	}
	return 0, false
}

// zhdatSmenu ждёт смерть старой копии (её pid передан аргументом --smena),
// прежде чем эта, уже повышенная копия займёт её место. Замена гонки
// (фиксированный time.Sleep(300ms) на стороне СТАРОЙ копии из прежней
// polnayaZashchita, без всякой обратной связи от новой) явным опросом:
// новая копия — та, что реально должна знать правду о смерти старой, а не
// наоборот. Не дождалась за srokOzhidaniyaSmeny — не виснем вечно, старая
// копия и правда могла зависнуть, но след в журнале обязателен: молчать о
// таком нельзя.
func zhdatSmenu(pid int) {
	predel := time.Now().Add(srokOzhidaniyaSmeny)
	for zhivProcess(pid) {
		if time.Now().After(predel) {
			log.Printf("смена режима: старая копия (pid %d) не завершилась за %s, занимаю её место всё равно", pid, srokOzhidaniyaSmeny)
			return
		}
		time.Sleep(100 * time.Millisecond)
	}
	log.Printf("смена режима: старая копия (pid %d) завершилась, занимаю её место", pid)
}

// snyatOsirotevshiySled чинит жёсткую смерть предыдущего запуска: Диспетчер
// задач, выключение/перезагрузка Windows (оконная сборка без консоли не
// получает SIGTERM) или пропадание питания не дают службе дойти до
// proksi.Snyat() в конце zapustitSluzhbu — реестр остаётся с ProxyEnable=1
// и нашим адресом, а ядра за ним уже нет. Жалоба 20.08 10:23 про закрытие
// приложения — эта же дыра, только для смерти без выхода.
//
// Три проверки подряд, и снимаем только если прошли все три:
//  1. metka.est — метка на диске есть: кто-то когда-то поставил прокси нашей
//     рукой или рукой ядра с нашим подтверждением (см. internal/proksi.Otmetit).
//     Нет метки — нам сюда вообще нечего смотреть, чужой прокси не наше дело.
//  2. !zhiva — живой копии службы нет. Если служба жива, прокси её и
//     трогать его отсюда, из процесса окна, — та самая дыра из 20.08.
//  3. proksi.Stoit(adres) — то, что СЕЙЧАС стоит в реестре, совпадает именно
//     с адресом из метки. Не совпадает (человек успел прописать свой прокси
//     после смерти нашей службы) — снимать НЕЧЕГО, чужой прокси не трогаем
//     никогда; метку при этом всё равно убираем, она устарела.
func snyatOsirotevshiySled(papka string) {
	adres, est := proksi.ProchestMetku()
	if !est {
		return
	}
	if _, zhiva := kopiya.Nayti(papka); zhiva {
		return
	}
	if !proksi.Stoit(adres) {
		proksi.UbratMetku()
		return
	}
	log.Printf("прошлый запуск умер жёстко и не снял системный прокси (%s), снимаю сам", adres)
	proksi.Snyat()
}

// snyatOsirotevshiySledTunnelya — та же беда, что чинит snyatOsirotevshiySled
// выше, но вопрос другой и ответ другой. Зовётся РАНЬШЕ него: не в окне, а на
// старте любой копии, включая служебную (см. вызов в main и его комментарий —
// именно на этом стенд 31.08 и поймал невыполненную уборку).
//
// У системного прокси авария 31.08 состояла в том, что запись ОСТАЛАСЬ и её
// надо СНЯТЬ. У туннеля снимать нечего и, по разбору ядра, оставаться нечему
// (см. шапку internal/tunnel): адаптер wintun принадлежит процессу ядра и
// уничтожается драйвером вместе с ним, а маршруты auto_route прописаны на
// LUID этого адаптера — нет адаптера, нет и маршрутов.
//
// Но разбор — это чтение чужого кода, а не замер, и молчаливое доверие
// собственному разбору уже стоило человеку интернета один раз за сутки.
// Поэтому проверяем приборно: след на диске говорит, что прошлая копия
// поднимала туннель и ушла НЕ штатно (штатный выход след снимает сам), а
// net.Interfaces() отвечает, жив ли ещё адаптер с этим именем.
//
// Адаптер жив — разбор неверен, и об этом надо сказать вслух в журнал, а не
// молчать: журнал уезжает разработчику суточной отправкой (internal/zhurnaly),
// и это единственный способ узнать правду с машины человека. Сам след
// снимается в обоих случаях: он описывает намерение прошлой копии, а не
// состояние системы, и хранить его дальше значит копить ложную тревогу.
func snyatOsirotevshiySledTunnelya(papka string) { uborkaSledaTunnelya(papka, nil) }

// uborkaSledaTunnelya — то же самое, но с подменяемой проверкой адаптера:
// случай «адаптер пережил процесс» иначе не проверить вовсе, а он тут самый
// важный. nil — боевая проверка (tunnel.Zhivoy, чтение net.Interfaces()).
func uborkaSledaTunnelya(papka string, zhiv tunnel.Adapter) {
	_, zhiva := kopiya.Nayti(papka)
	itog := tunnel.UbratOsirotevshiy(zhiva, zhiv)
	if !itog.BylSled {
		return
	}
	if itog.AdapterVisit {
		log.Printf("ВНИМАНИЕ: прошлый запуск умер жёстко, а сетевой адаптер туннеля %q ЖИВ — "+
			"разбор ядра обещал, что адаптер уходит вместе с процессом; проверьте маршрутизацию", itog.Adapter)
		return
	}
	log.Printf("прошлый запуск умер жёстко в туннельном режиме; адаптер %q не пережил процесс, "+
		"маршрутизация чистая — убрал только след на диске", itog.Adapter)
}

// ubratHvostProshlogoObnovleniya убирает <имя>.old, оставшийся от прошлого
// тычка в пузырь (obnovlenie.Postavit переименовывает старый файл, а не
// удаляет — пока он был запущен, удалить было нельзя). Раньше эту же строку
// звал obnovitsya() на каждом холодном старте попутно со своей автоматической
// подменой .exe (см. её комментарий в main()); теперь это единственное, что
// здесь осталось от того пути — тихо, без сети и не блокируя запуск.
func ubratHvostProshlogoObnovleniya() {
	put, err := obnovlenie.PutSebya()
	if err != nil {
		log.Printf("уборка хвоста обновления: не знаю, где лежу: %v", err)
		return
	}
	obnovlenie.UbratHvost(put)
}

// ubratHvostPosleSmeny — та же уборка, но в единственной точке, где хвост
// ОБЯЗАН убраться: новая копия только что дождалась подтверждённой смерти
// старой (zhdatSmenu), и файл, который держала та копия, свободен.
//
// Здесь уборка не «попутная тишина», как на холодном старте, а исполнение
// обещания человеку: жалоба 02.09 начинается с того, что рядом с приложением
// остаётся лежать <имя>.old. Поэтому и повторы (освобождение файла на Windows
// отстаёт от смерти процесса), и разговор вслух при неудаче: молча оставить
// хвост на виду — значит повторить ту самую жалобу и не оставить следа, по
// которому её потом разбирать.
func ubratHvostPosleSmeny() {
	put, err := obnovlenie.PutSebya()
	if err != nil {
		log.Printf("уборка хвоста после смены: не знаю, где лежу: %v", err)
		return
	}
	if !obnovlenie.HvostEst(put) {
		// Смена ради ПРАВ (--smena после UAC), а не ради обновления: файл никто
		// не подменял, убирать нечего. Молчим — строка «убрал» там, где ничего
		// не было, соврала бы в журнале, который потом и разбирают.
		return
	}
	if obnovlenie.UbratHvostSPovtorami(put) {
		log.Printf("уборка хвоста после смены: прошлая сборка убрана, рядом с приложением чисто")
		return
	}
	log.Printf("ВНИМАНИЕ: хвост прошлого обновления рядом с %s убрать не вышло — он останется на виду у человека "+
		"до следующего запуска (уберёт ubratHvostProshlogoObnovleniya)", put)
}

// estArg — есть ли такой флаг среди os.Args.
func estArg(arg string) bool {
	for _, a := range os.Args[1:] {
		if a == arg {
			return true
		}
	}
	return false
}

// nuzhnoSprositPravaNaStarte решает, спросить ли права администратора сразу
// на обычном старте (заказ 29.08: подтверждение прав должно вылезать при
// старте программы и больше не мешать), а не откладывать до первого
// подключения (internal/sluzhba.zaprositPravaAvtomaticheskiEsliNado — этот
// путь у СУЩЕСТВУЮЩИХ установок не сработает никогда: hranenie.Zagruzit
// метит их «уже спрашивали» ещё на миграции) или до клика по кнопке
// «Включить для всех программ».
//
// Чистая функция — решение проверяется тестом без настоящего UAC и без сети:
//
//	estPrava          — права уже есть (prava.Est()), спрашивать нечего.
//	tiho              — автообновление (--tiho --smena) или автозапуск с
//	                     Windows (--tiho) — не человек только что открыл окно.
//	smenaPID          — эта копия уже И ЕСТЬ смена режима (после UAC либо
//	                     после обновления), спрашивать второй раз подряд нельзя.
//	estChuzhayaKopiya — рядом уже висит живая копия: человек кликнул значок
//	                     в трее у неё, а не запустил программу с нуля —
//	                     показывать UAC в ответ на клик по трею нельзя.
func nuzhnoSprositPravaNaStarte(estPrava, tiho bool, smenaPID int, estChuzhayaKopiya bool) bool {
	if estPrava || tiho || smenaPID > 0 || estChuzhayaKopiya {
		return false
	}
	return true
}

// poprositPravaPriStarte — хук вместо прямого internal/prava.PoprositPriStarte,
// подменяется в тесте (см. main_test.go), чтобы не дёргать настоящий UAC.
var poprositPravaPriStarte = prava.PoprositPriStarte

// sprositPravaNaStarte исполняет решение nuzhnoSprositPravaNaStarte: просит
// права и в любом случае (согласие или отказ) метит настройки «уже
// спрашивали» — тем же порядком, что и автозапрос при первом подключении
// (sluzhba.go: zaprositPravaAvtomaticheskiEsliNado) — отметку пишем ДО ухода,
// иначе следующий, уже обычный запуск снова увидит файл без отметки и
// спросит ещё раз, а человек просил ровно один раз.
//
// Возвращает true, если эта копия должна немедленно уйти: человек согласился
// в UAC, новая, уже повышенная копия поднимется сама. В этой точке main ещё
// не открыл окно и не поднял службу (вызов стоит ДО adresKopii) — уйти можно
// простым return, снимать нечего.
func sprositPravaNaStarte(papka string) bool {
	nastroyki, err := hranenie.Zagruzit()
	if err != nil {
		log.Printf("запрос прав при старте: не прочитал настройки, не спрашиваю: %v", err)
		return false
	}
	oshibka := poprositPravaPriStarte(os.Getpid())
	if oshibka != nil {
		log.Printf("запрос прав администратора при старте: отказ или ошибка: %v — продолжаю без прав", oshibka)
	} else {
		log.Printf("человек согласился на права администратора при старте, перезапускаюсь")
	}
	nastroyki.OtmetitPravaZaprosheny()
	if err := hranenie.Sohranit(nastroyki); err != nil {
		log.Printf("запрос прав при старте: не сохранил отметку об автозапросе: %v", err)
	}
	return oshibka == nil
}

// podnyatSluzhbuOtdelno запускает службу отдельным процессом (zapusk_windows.go
// / zapusk_other.go) и ждёт, пока она отметится меткой копии — так же, как
// это видит следующий двойной щелчок пользователя.
func podnyatSluzhbuOtdelno(papka string) (string, error) {
	if err := zapustitOtdelnuyuSluzhbu(); err != nil {
		return "", err
	}
	predel := time.Now().Add(srokPodnyatiyaSluzhby)
	for time.Now().Before(predel) {
		if adres, est := kopiya.Nayti(papka); est {
			log.Printf("служба поднялась отдельным процессом: %s", adres)
			return adres, nil
		}
		time.Sleep(200 * time.Millisecond)
	}
	return "", fmt.Errorf("не дождался метки службы за %s", srokPodnyatiyaSluzhby)
}

// zapustitSluzhbu — режим --sluzhba (и его синоним KELEVRA_BEZ_OKNA=1):
// ядро, HTTP-служба и ожидание сигнала остановки, без окна и без проверки
// обновлений (её уже сделала копия, которая эту службу подняла).
//
// Это единственное место, где ставится системный прокси, поэтому и снимать
// его при выходе (штатном и аварийном) должно только оно — иначе процесс окна
// снимал бы прокси, который поставил не он, и делал бы это на закрытии
// крестиком, что и было исходной бедой.
func zapustitSluzhbu(papka, putZhurnala string) {
	// Обычный служебный процесс: живёт в сеансе человека, показывает значок
	// в трее и сам снимает системный прокси за собой.
	rabotaSluzhby(context.Background(), papka, putZhurnala, true)
}

// rabotaSluzhbyWindows — то же самое, но под диспетчером служб Windows.
//
// Отличий ровно два, и оба вынужденные. Значка в трее нет: у службы нет
// интерактивного сеанса, показывать его некому и негде. Системный прокси не
// снимается: он лежит в ветке реестра ПОЛЬЗОВАТЕЛЯ, а служба работает под
// системной учётной записью и попала бы в чужой профиль — ставит и снимает
// его оконная часть, она же и убирает осиротевший след.
func rabotaSluzhbyWindows(ctx context.Context, papka, putZhurnala string) {
	rabotaSluzhby(ctx, papka, putZhurnala, false)
}

// rabotaSluzhby — общее тело обоих режимов. vneshniy отменяется, когда работу
// пора сворачивать: у службы Windows это команда диспетчера, у обычного
// процесса он бессрочный, и остановку приносит сигнал или «Выход» из трея.
func rabotaSluzhby(vneshniy context.Context, papka, putZhurnala string, sTreem bool) {
	s, err := sluzhba.Novaya()
	if err != nil {
		umeret(putZhurnala, "Kelevra не смогла подготовить свои файлы", err)
	}
	// Хук подключается тут, а не живёт внутри internal/sluzhba: пакет sluzhba
	// про трей и Windows ничего не знает (см. комментарий поля). На Windows
	// это настоящий пузырь (trey_windows.go), на остальных платформах — след
	// в журнале для стенда (trey_other.go); обе реализации лежат в одном
	// пакете main, поэтому здесь имя одно и то же независимо от ОС.
	s.OblachkoObnovleniya = pokazatOblachkoObnovleniya
	s.MetkaObnovleniya = pometitObnovlenie
	// Значок обязан различать полную защиту и половинную (31.08, «впн не
	// выполняет свою основную функцию»): подсказка была константой и звучала
	// одинаково в обоих режимах — см. cmd/kelevra/metka_zashchity.go.
	s.MetkaZashchity = pometitZashchitu
	s.PerezapuskPosleObnovleniya = zapustitSmenuPosleObnovleniya
	// Тычок в пузырь трея зовёт этот же метод напрямую (trey_windows.go:
	// tychokVPuzyr) — пакет trey про internal/sluzhba ничего не знает, тем же
	// принципом, что и OblachkoObnovleniya выше.
	ustanovitObnovlenie = s.PostavitNaydennoe
	slushatel, url, err := s.Slushat()
	if err != nil {
		umeret(putZhurnala, "Kelevra не смогла занять локальный порт (обычно это фаервол или антивирус)", err)
	}
	server := &http.Server{Handler: s.Obsluzhit()}
	go func() {
		if err := server.Serve(slushatel); err != nil && err != http.ErrServerClosed {
			log.Printf("служба остановилась: %v", err)
		}
	}()
	if err := kopiya.Zanyat(papka, url, time.Now()); err != nil {
		log.Printf("не смог отметить запуск (второй запуск не будет пойман): %v", err)
	}
	defer kopiya.Osvobodit(papka)

	ctx, otmena := context.WithCancel(vneshniy)
	defer otmena()
	go s.ObnovlyatProfil(ctx)
	// Копия, которую человек не закрывал днями, никогда больше не проходит
	// obnovitsya() (он звучит один раз при холодном старте, выше по main()) —
	// без этой строки 0.6.23 и 0.6.24 не долетели бы до него никогда, сколько
	// бы дней приложение ни висело в трее. Только СПРАШИВАЕТ и запоминает
	// находку для /api/sostoyanie — не ставит сама (см. комментарий метода).
	go s.SleditZaObnovleniem(ctx, periodFonovoyProverki())
	// Раз в сутки, в конце дня, копия отдаёт свои журналы разработчику
	// (internal/zhurnaly). Тот же ctx, что у двух горутин выше — defer
	// otmena() гасит всех троих разом. Тумблер человека проверяется внутри,
	// на каждом тике: выключил — следующий же тик промолчит.
	go s.SleditZaZhurnalami(ctx, sluzhba.ShagSlezhkiZaZhurnalami)
	// Раз в минуту копия спрашивает у ядра его счётчики и копит СВОЙ расход:
	// сервер считает трафик по ключу доступа, а под ключом ходит ещё и
	// телефон — сколько прогнал именно этот компьютер, знает только он сам.
	go s.SchitatTrafik(ctx, sluzhba.ShagUchetaTrafika)

	// Авторежим по умолчанию выключен (см. hranenie.Nastroyki.Avtorezhim) —
	// заводим служителя, только если человек сам его включил в прошлый раз.
	// Останавливать отдельно не нужно: служитель слушает тот же ctx, что
	// ObnovlyatProfil выше, и defer otmena() гасит обоих разом.
	if s.Nastroyki.Avtorezhim {
		s.ZapustitAvtorezhim(ctx)
	}

	log.Printf("служба слушает %s", url)
	fmt.Println("KELEVRA-SLUZHBA", url)

	// Значок в трее — обязательное завершение переделки из b924080: без
	// него служба живёт невидимкой (закрыл окно — защита работает, но
	// понять это и выключить нечем). Своя горутина со своим recover: отказ
	// трея (включая Windows без explorer.exe, как на моём стенде под wine)
	// не имеет права уронить службу с прокси.
	if sTreem {
		vyhodIzTreya := make(chan struct{}, 1)
		go func() {
			defer func() {
				if r := recover(); r != nil {
					log.Printf("трей: авария в потоке значка, продолжаю без него: %v\n%s", r, debug.Stack())
				}
			}()
			zapustitTrey(vyhodIzTreya)
		}()

		zhdatSignal(vyhodIzTreya)
	} else {
		// Служба Windows: остановку приносит диспетчер служб отменой контекста.
		// Сигналы сюда не доходят вовсе, а значка в трее нет по устройству:
		// интерактивного сеанса у службы не бывает.
		<-vneshniy.Done()
		log.Printf("служба Windows: диспетчер попросил остановиться")
	}

	_ = s.Yadro.Ostanovit()
	if sTreem {
		// Ядро гасится жёстко и откатить системный прокси за собой не успевает.
		// Без этой строки после закрытия приложения у человека перестают
		// открываться сайты (жалоба 20.08).
		proksi.Snyat()
		// В службе Windows этой строки нет намеренно: системный прокси лежит
		// в ветке реестра ПОЛЬЗОВАТЕЛЯ, и снимать его из-под системной учётной
		// записи значит промахнуться мимо профиля человека.
	}
	// След туннеля — той же природы: ядро ушло, адаптер вместе с ним, и
	// следующий запуск не должен искать то, чего мы сами штатно убрали.
	tunnel.UbratMetku()
}

// zhdatSignal держит служебный режим живым до Ctrl+C, остановки извне или
// «Выход» из значка в трее (vyhodIzTreya) — оба пути должны довести дело до
// одного и того же штатного завершения ниже (Ostanovit + Snyat), а не
// выйти через os.Exit из чужого потока.
func zhdatSignal(vyhodIzTreya <-chan struct{}) {
	stop := make(chan os.Signal, 1)
	signal.Notify(stop, os.Interrupt, syscall.SIGTERM)
	select {
	case <-stop:
		log.Printf("служебный режим: получен сигнал, останавливаюсь")
	case <-vyhodIzTreya:
		log.Printf("служебный режим: «Выход» из трея, останавливаюсь")
	}
}

// umeret — единственный выход из строя, который видит пользователь.
// Просто упасть приложение не имеет права: у оконной сборки нет консоли,
// и «ничего не произошло» — это всё, что человек увидел бы вместо причины.
func umeret(putZhurnala, chto string, err error) {
	log.Printf("ОТКАЗ: %s: %v", chto, err)
	tekst := chto + ".\n\n" + err.Error()
	if putZhurnala != "" {
		tekst += "\n\nПодробности записаны в файл:\n" + putZhurnala
	}
	skazat("Kelevra не запустилась", tekst)
	os.Exit(1)
}

// lovitPaniku превращает аварию в текст на экране и строку в журнале.
// Ловится только авария главной горутины — этого хватает для старта,
// где и случается почти всё, что может пойти не так у пользователя.
//
// snyatProksi — этот процесс сейчас служба (единственная, кто ставит системный
// прокси)? Процесс окна прокси не ставил и снимать чужой не должен: иначе
// авария окна (или само его закрытие) гасила бы защиту, которую поднял
// отдельный процесс службы, — та же дыра, которую разводит вся эта переделка.
func lovitPaniku(putZhurnala string, snyatProksi bool) {
	r := recover()
	if r == nil {
		return
	}
	log.Printf("АВАРИЯ: %v\n%s", r, debug.Stack())
	tekst := fmt.Sprintf("Kelevra аварийно остановилась.\n\n%v", r)
	if putZhurnala != "" {
		tekst += "\n\nПодробности записаны в файл:\n" + putZhurnala
	}
	skazat("Kelevra остановилась", tekst)
	if snyatProksi {
		// os.Exit минует код после lovitPaniku в main (там же снимается
		// прокси), а авария ядра оставляет системный прокси включённым точно
		// так же, как обычное закрытие окна — снимаем его и на этом пути.
		proksi.Snyat()
		// Метку туннеля НЕ снимаем: этот путь заканчивается os.Exit(2), то
		// есть ядро остаётся жить сиротой ровно до тех пор, пока его не
		// прибьёт ОС. Снятый след соврал бы следующему запуску, что туннеля
		// не было; оставленный заставит его ПРОВЕРИТЬ адаптер приборно
		// (snyatOsirotevshiySledTunnelya) — а это ровно то, что тут нужно.
	}
	os.Exit(2)
}

// tihiyZapusk отвечает на единственный вопрос запуска: показывать ли окно.
// Вынесено из main отдельной функцией не ради красоты — это место я ломал
// дважды за три дня, каждый раз чиня прошлую поломку:
//
//	25.08 (7f31c1c): жалоба на два открытых окна — при смене режима на
//	      секунды показывались два окна разом. Закрыл её тем, что новая копия
//	      стала молчать ВСЕГДА: `tiho := estArg(argTiho) || estSmena`.
//	27.08: жалоба, что окно не работает до перезапуска, — то самое
//	      «всегда» съело и окно после смены ПРАВ, ради которой человек и жал
//	      кнопку. Лечение прошлой болезни стало новой болезнью.
//
// Различие между двумя случаями лежало в коде всё это время, ровно в одном
// флаге: автообновление шлёт `--tiho --smena <pid>` (obnovlenie.go:
// zapustitSmenuPosleObnovleniya), а смена прав после UAC — только
// `--smena <pid>` (internal/prava: Poprosit). --smena сообщает ПРИЧИНУ
// перезапуска, а нужно ли окно — несёт свой собственный флаг --tiho, и
// подменять один другим нельзя.
//
// Сама по себе это одна строка; ценность в том, что её теперь держит тест
// (main_test.go) на всех четырёх наборах аргументов, какие приложение реально
// себе шлёт. Третьего раза в этом месте быть не должно.
func tihiyZapusk(args []string) bool {
	for _, a := range args {
		if a == argTiho {
			return true
		}
	}
	return false
}

// priStarteZapusk — тот же разбор, что и tihiyZapusk, но для argPriStarte:
// эта копия поднята запросом прав СРАЗУ ПРИ СТАРТЕ (sprositPravaNaStarte), а
// не кнопкой «Включить для всех программ» (см. её комментарий у константы).
func priStarteZapusk(args []string) bool {
	for _, a := range args {
		if a == argPriStarte {
			return true
		}
	}
	return false
}
