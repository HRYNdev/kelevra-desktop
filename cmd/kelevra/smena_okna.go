package main

// Передача окна при смене копии — то место, где обновление теряло окно.
//
// Жалоба 02.09: «нажимаешь на обновление — и всё», рядом появляется файл с
// хвостом .old, а работающего приложения не видно; помогает только закрыть и
// открыть руками. Разбор журнала с машины владельца, строки подряд:
//
//	[окно] смена режима: старая копия (pid …) завершилась, занимаю её место
//	[окно] смена режима: отправил WM_CLOSE окну прошлой копии (hwnd=…)
//	[служба] запуск Kelevra …
//	[окно] поиск окна: FindWindowW не нашёл окно (класс "webview", заголовок "Kelevra")
//
// Окно прошлой копии закрыли, а своё не открыли ни разу: FindWindowW восемью
// секундами позже честно не нашёл ничего, потому что искать было нечего.
// Класс и заголовок тут ни при чём — их никто не меняет (go-webview2
// регистрирует класс "webview" один раз, а SetTitle после создания окна не
// зовётся ни разу, см. okno_windows.go). Причина — один флаг: установка
// обновления поднимает смену как `--tiho --smena <pid>` (obnovlenie.go:
// zapustitSmenuPosleObnovleniya), а --tiho значит «окна никто не просил»
// (main.go: tihiyZapusk), и до pokazatOkno main не доходит вовсе.
//
// Флаг был верен, пока обновление ставилось САМО на холодном старте: окна
// тогда и правда никто не просил. С 26.08 обновление ставит человек нажатием,
// и жмёт он его, глядя в открытое окно, — молчание в ответ на его нажатие и
// есть беда.
//
// Чинится не снятием --tiho (тогда молчаливый автозапуск с Windows начал бы
// открывать окно каждому входу в систему) и не новым флагом от службы (служба
// не знает, открыто ли у человека окно прямо сейчас), а ЗАМЕРОМ, который
// смена и так делает: она ищет окно прошлой копии, чтобы его закрыть
// (zakrytStaroeOkno). Нашла — человек смотрел в окно, и новая копия обязана
// вернуть ему окно взамен закрытого. Не нашла — тычок пришёл из трея при
// закрытом окне, и открывать нечего.

// itogSmenyOkna — что смена застала и что сделала с окном ПРЕДЫДУЩЕЙ копии.
// Два разных вопроса, и оба нужны отдельно:
//
//	BylOkno — окно прошлой копии на экране БЫЛО. Отсюда и только отсюда
//	          новая копия узнаёт, ждёт ли человек окна взамен.
//	Ushlo   — оно и правда исчезло с экрана к моменту возврата. Ложь тут
//	          означала бы второе окно поверх первого — ровно ту беду, ради
//	          которой смена вообще закрывает чужое окно.
//
// Нулевое значение (окна не было) годится как ответ платформ без окон —
// см. okno_other.go.
type itogSmenyOkna struct {
	BylOkno bool
	Ushlo   bool
}

// pokazatLiOkno — показывать ли окно этой копии. Решение, а не исполнение:
// его держит тест (main_test.go) на всех наборах аргументов, какие приложение
// шлёт себе само, и на обоих исходах замера окна.
//
//	tiho     — пришёл флаг --tiho: «окна никто не просил».
//	smenaPID — эта копия поднята сменой (после UAC или после обновления).
//	itog     — что смена застала на экране (см. itogSmenyOkna).
//
// Единственное послабление для --tiho — смена, унаследовавшая ОТКРЫТОЕ окно.
// Молчаливый автозапуск с Windows (--tiho без --smena) окна не открывает
// по-прежнему: там окна не было и человек ничего не нажимал.
func pokazatLiOkno(tiho bool, smenaPID int, itog itogSmenyOkna) bool {
	if !tiho {
		return true
	}
	return smenaPID > 0 && itog.BylOkno
}
