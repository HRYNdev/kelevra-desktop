package avtorezhim

// Sledchik — слежение за сменой сети. Каждое значение в канале — сигнал
// «с сетью что-то изменилось, стоит перепроверить обстановку заново»; сам
// канал не говорит, что именно изменилось — [Avtorezhim.Zahod] всё равно
// спрашивает DNS-зонд и прямой трафик заново целиком, точно как в
// AutoMode.kt: onNetworkChanged будит заход, а не пытается угадать ответ по
// типу события.
type Sledchik interface {
	// Sobytiya — канал, в который приходит по одному значению на каждую
	// замеченную смену сети. Закрывается вызовом Stop.
	Sobytiya() <-chan struct{}
	// Stop останавливает слежение и закрывает канал Sobytiya.
	Stop()
}
