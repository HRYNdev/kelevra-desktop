// Приведение защиты к обстановке — то, чего в этом пакете не хватало.
//
// Раньше связка была СОБЫТИЙНОЙ: [Sluzhitel] звал колбэк только когда
// [Zadvizhka] действительно переехала (Zahod вернул izmenilos == true).
// Пока обстановка меняется — работает; беда в том, что обстановка может
// УЖЕ стоять на нужном значении, а защита ему не соответствовать, и тогда
// событийная связка молчит вечно. Обычные способы попасть в такую яму, все
// боевые:
//
//   - человек нажал «Подключиться» дома: кнопка (Sluzhba.podklyuchit)
//     завела задвижку сразу на Doma, а поднятую в прошлый раз защиту никто
//     не опустил — смены обстановки больше не будет, значит и колбэка тоже;
//   - опускание защиты не удалось с первого раза (ядро не умерло) —
//     задвижка уже на Doma, второй попытки не будет никогда;
//   - человек поднял защиту руками поверх работающего автомата, стоящего
//     на Doma;
//   - пачка слепых заходов (туннель поднят, физический адаптер ещё не
//     опознан) съела ровно тот заход, на котором обстановка переехала бы.
//
// Ровно на это жалоба, повторённая четырежды (25.08, 28.08, 29.08,
// 30.08): при переключении обратно на домашний Wi-Fi VPN не выключался.
//
// Лечение перенесено с телефона дословно. Там [AutoMode.round] зовёт
// apply(host, situation, repeat) НА КАЖДОМ круге, а не только при смене
// (AutoMode.kt:1289-1293 при changed и :1262-1275 при repeat = true), и
// ветка Situation.Home внутри apply (:1681-1690) идемпотентно гасит туннель
// вызовом host.suspendTunnel("дома обход делает роутер") — специально и на
// повторе тоже, потому что туннель мог подняться помимо автомата.
//
// Здесь то же самое разложено на две части: чистое правило [Nuzhno] (что
// нужно сделать, чтобы защита отвечала обстановке) и [Sluzhitel.Primenit]
// (кто это делает). Правило чистое нарочно — оно проверяется таблицей,
// без сети, ядра и HTTP.

// Deystvie — что нужно сделать с защитой, чтобы она отвечала обстановке.
type Deystvie int

const (
	// NeTrogat — защита уже такая, какой обстановка её хочет (или обстановка
	// неизвестна): ничего не делаем. Тишина здесь — не бездействие, а
	// единственно верный ответ: лишний рестарт ядра рвёт живые соединения.
	NeTrogat Deystvie = iota

	// Opustit — дома, а защита поднята: опустить. Обход блокировок дома уже
	// делает роутер, туннель поверх него — обёртка поверх обёртки.
	Opustit

	// Podnyat — вне дома, а защиты нет: поднять.
	Podnyat
)

func (d Deystvie) String() string {
	switch d {
	case Opustit:
		return "опустить защиту"
	case Podnyat:
		return "поднять защиту"
	default:
		return "не трогать защиту"
	}
}

// Nuzhno — правило приведения: что сделать с защитой, чтобы она отвечала
// обстановке s, если прямо сейчас она поднята (zashchitaPodnyata).
//
// [Neizvestno] НИКОГДА ничего не требует — это перенос той же осторожности,
// что и в [Reshit] и в [Zadvizhka.Predlozhit]: неизвестность не повод дёргать
// чужой туннель. Броня против молчащих резолверов (см. Nablyudeniye.DnsMolchit,
// авария 28.08) от приведения не страдает и не может: молчание даёт
// Neizvestno на уровне НАБЛЮДЕНИЯ, задвижка его не пропускает, и в Nuzhno
// приходит та обстановка, на которой задвижка стояла и раньше, — приведение
// работает по УЖЕ принятому решению, а не по сырому наблюдению.
func Nuzhno(s Sostoyanie, zashchitaPodnyata bool) Deystvie {
	switch s {
	case Doma:
		if zashchitaPodnyata {
			return Opustit
		}
	case VneDoma:
		if !zashchitaPodnyata {
			return Podnyat
		}
	}
	return NeTrogat
}
