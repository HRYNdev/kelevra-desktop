// Сторож бюджета кнопки «Подключиться».
//
// Беда 28.08, словами хозяина: «нажимаю подключиться, он не определяет дома».
// Замер показал причину: подзонды авторежима идут последовательно на ОДНОМ
// ctx, а кнопка давала на весь заход 5с при номиналах 3с DNS + 4с трафик.
// Сколько DNS съел — столько минус оставалось прямому зонду, и один и тот же
// честный ответ давал разный вердикт: «DNS съел 50мс -> дома; DNS съел 280мс
// (тот же честный ответ, просто дольше) -> вне дома».
//
// Лечится это не разрывом ctx (проверено и отвергнуто: без общего дедлайна
// зависший зонд висит вечно и кнопка не поднимает защиту НИКОГДА — см.
// TestPodklyuchitTaimautVsyoRavnoPodnimaetZashchitu), а размером бюджета.
// Условие «бюджет >= сумма номиналов» живёт в двух разных файлах и разных
// пакетах, поэтому его легко разъехать молча: кто-то поднимет номинал зонда
// и не тронет таймаут кнопки. Этот стенд краснеет ровно на таком расхождении.
package sluzhba

import (
	"testing"

	"github.com/HRYNdev/kelevra-desktop/internal/avtorezhim"
)

func TestKnopkaVmeshchaetSummuNominalovZondov(t *testing.T) {
	s := &Sluzhba{}
	a := s.avtorezhimBoevoy()

	dns, ok := a.Dns.(*avtorezhim.DnsZond)
	if !ok {
		t.Fatalf("боевой авторежим собран с DNS-зондом типа %T — стенд не умеет прочитать его номинал, поправь стенд, а не выкидывай его", a.Dns)
	}
	trafik, ok := a.Trafik.(*avtorezhim.PryamoyZond)
	if !ok {
		t.Fatalf("боевой авторежим собран с трафик-зондом типа %T — стенд не умеет прочитать его номинал, поправь стенд, а не выкидывай его", a.Trafik)
	}
	if dns.Taimaut <= 0 {
		t.Fatalf("номинал DNS-зонда %v: стенд не может сложить номиналы, а значит и не сторожит ничего", dns.Taimaut)
	}
	if trafik.Taimaut <= 0 {
		t.Fatalf("номинал прямого зонда %v: стенд не может сложить номиналы, а значит и не сторожит ничего", trafik.Taimaut)
	}

	summa := dns.Taimaut + trafik.Taimaut
	if KnopkaTaimautPoUmolchaniyu < summa {
		t.Fatalf("бюджет кнопки «Подключиться» %v меньше суммы номиналов подзондов (%v DNS + %v трафик = %v).\n"+
			"Это ровно беда 28.08: подзонды идут последовательно на одном ctx, и честно медленный DNS отнимает у прямого зонда его законное время — вердикт переворачивается на «не дома» без всякой вины сети.\n"+
			"Чинить надо KnopkaTaimautPoUmolchaniyu (или номинал зонда), а не этот стенд.",
			KnopkaTaimautPoUmolchaniyu, dns.Taimaut, trafik.Taimaut, summa)
	}
}
