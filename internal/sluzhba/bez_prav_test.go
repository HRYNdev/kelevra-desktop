package sluzhba

import (
	"testing"

	"github.com/HRYNdev/kelevra-desktop/internal/prava"
)

// nuzhenChelovekBezPrav пропускает проверку, если она идёт ОТ АДМИНИСТРАТОРА.
//
// Зачем понадобилось 08.09. В этот день гейт наконец начал гонять тесты на
// настоящей Windows (до этого — только на линуксе, где весь windows-путь
// подменён заглушками). И сразу шесть проверок покраснели, хотя продукт был
// цел: они описывают поведение приложения БЕЗ прав администратора — просит
// ли оно права, как ведёт себя после отказа, ставит ли системный прокси. А
// раннер GitHub работает под администратором, и prava.Est() там честно
// отвечает «права есть»: обработчик до запроса прав не доходит вовсе, и
// измерять становится нечего.
//
// Пропуск, а не переписывание: сами проверки верные и на линуксе (и на машине
// человека, где приложение запускают обычным пользователем) продолжают
// работать. Молча краснеть на среде, для которой они не писались, — значит
// приучить себя не смотреть на красное.
func nuzhenChelovekBezPrav(t *testing.T) {
	t.Helper()
	if prava.Est() {
		t.Skip("идём от администратора: ветка запроса прав тут не воспроизводится (раннер Windows)")
	}
}
