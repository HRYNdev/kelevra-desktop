// Приём живого ядра при старте копии — то, ради чего заведена yadro.Peredacha.
//
// Зачем. Туннель держит ядро, отдельный процесс, переживающий смену оболочки.
// Обновляется оболочка. Значит при обновлении туннелю падать незачем — и с
// 11.09.2026 он не падает: старая копия уходит, не гася ядро, а новая
// принимает его по записке. Замер на стенде в тот день показал цену прежнего
// порядка: восемь секунд без туннеля, причём незаметных (связь не пропадала,
// трафик шёл напрямую мимо обхода), а после обновления туннель не
// возвращался вовсе.
//
// Зовётся на старте службы, ДО авторежима и до любого решения о подключении:
// если ядро уже работает, то решать нечего — связь есть, и её надо не
// поднимать заново, а взять.

// PrinyatZhivoeYadro берёт под управление ядро прошлой копии, если оно живо.
//
// Три исхода, и каждый ведёт себя по-своему:
//   - приняли: связь не прерывалась, эта копия теперь ей хозяин;
//   - конфиг ядра устарел: связь тоже не прерываем, но меняем ядро ПЛАВНО —
//     поднимаем новое рядом и гасим старое только после того, как новое
//     заработало;
//   - принимать нечего или не наше: молча уходим, дальше всё как раньше.
func (s *Sluzhba) PrinyatZhivoeYadro(ctx context.Context) {
	papka := hranenie.PapkaYadra()
	p, est := yadro.ProchestPeredachu(papka)
	if !est {
		return // записки нет — обычный холодный старт
	}

	itog := s.Yadro.Prinyat(p, s.otpechatokZhelaemogoKonfiga())
	switch {
	case itog.Prinyato:
		// Метку туннеля перезаписываем СВОИМ номером процесса: она отвечает
		// на вопрос «чья это связь», и оставить в ней номер умершей копии
		// значит соврать следующему запуску, который по ней решает, сирота
		// перед ним или живой хозяин.
		if p.Adapter != "" {
			zakrepitTunnel(p.Adapter)
		}
		s.soobshchitTreyuProZashchitu(true)

	case itog.KonfigUstarel:
		s.smenitYadroPlavno(ctx, p)

	default:
		// Не опознали. Чаще всего это просто протухшая записка от ядра,
		// которое давно умерло, — тогда и делать нечего. Но если по этой
		// записке процесс ЖИВ и это наш бинарь, а принять мы его не смогли,
		// на машине остался бы хозяин без головы: связь работает, а
		// управлять ею некому и выключить её человек не может. Такое гасим.
		log.Printf("живое ядро не принято (%s)", itog.Pochemu)
		if _, zhivo := yadro.ZhivoPoZapiske(papka); zhivo {
			log.Printf("ядро из записки живо, но управлять им отсюда нельзя — гашу, чтобы не осталось без хозяина")
			yadro.PogasitChuzhoe(p.PID)
		}
		yadro.UbratPeredachu(papka)
	}
}

// dobavitPravilaIzKesha кладёт в выбор правила, уже лежащие на диске.
//
// Отдельным методом, а не строками внутри PodnyatZashchitu, ровно потому, что
// зовётся из двух мест и разъехаться им нельзя: подъём ядра собирает по нему
// НАСТОЯЩИЙ конфиг, а приём живого ядра — конфиг ЖЕЛАЕМЫЙ, чтобы сверить его
// с тем, по которому ядро уже работает. Разойдись эти две сборки — и сверка
// объявляла бы конфиг сменившимся на ровном месте, то есть меняла бы ядро
// там, где его надо просто принять.
//
// vsluh — писать ли в журнал. Подъёму это нужно (возраст кеша в журнале был
// единственным способом проверить жалобу «списки никогда не обновляются»), а
// сверке при приёме нечего сказать человеку: она ничего не меняет.
func (s *Sluzhba) dobavitPravilaIzKesha(vybor *konfig.Vybor, vsluh bool) {
	kesh := pravila.IzKesha(hranenie.PapkaYadra(), s.tegiPravil())
	if kesh == nil {
		return
	}
	vybor.PravilaIzKomplekta = kesh
	vybor.PravilaKomplektData = "" // не комплект, а свежие с диска — заметку не показываем
	if !vsluh {
		return
	}
	log.Printf("правила беру из кеша на диске (%d наборов, последняя сверка с сервером %s назад) — ядру не придётся качать их на старте",
		len(kesh), okruglit(pravila.Vozrast(hranenie.PapkaYadra(), s.tegiPravil())))
	s.zamok.Lock()
	s.svezhihPravil = 0 // применили: то, что лежало на диске, теперь в работе
	s.zamok.Unlock()
}

// otpechatokZhelaemogoKonfiga — каким был бы конфиг, подними эта копия ядро
// сама, прямо сейчас.
//
// Считается В ПАМЯТИ и ничего не записывает: на диске в этот момент лежит
// черновая сборка стартующей копии, и сверяться с ней нельзя (замер 11.09.2026
// — см. Yadro.Prinyat). Пусто, если посчитать не вышло: тогда приём обходится
// без сверки конфига, что честнее, чем оборвать работающую связь из-за
// неизвестности.
func (s *Sluzhba) otpechatokZhelaemogoKonfiga() string {
	syroy, err := os.ReadFile(hranenie.PutProfilya())
	if err != nil {
		return ""
	}
	vybor := konfig.Vybor{Prava: s.estPrava()}
	s.dobavitPravilaIzKesha(&vybor, false)
	gotovyy, _, err := konfig.Prigotovit(syroy, vybor)
	if err != nil {
		return ""
	}
	return yadro.OtpechatokKonfigaBayt(gotovyy)
}

// smenitYadroPlavno меняет живое ядро на новое, не разрывая связь.
//
// Случай редкий: конфиг между версиями обычно не меняется вовсе, он
// собирается из профиля и настроек, а не из версии приложения. Но когда всё же
// изменился, принять старое ядро нельзя — человек молча остался бы на прежних
// правилах, — и рвать связь ради этого тоже незачем.
//
// Порядок ровно обратный прежнему «погасили и подняли»: сперва поднимаем
// новое ядро РЯДОМ с живым, и только когда оно заработало, гасим старое. Имя
// адаптера подбирается само: занятое прежним ядром имя приложение видит и
// берёт соседнее свободное (internal/tunnel.SvobodnoeImya) — тот же механизм,
// что чинил занятые имена после жёсткой смерти.
//
// Если новое ядро подняться не смогло, старое НЕ трогаем: пусть человек
// останется на прежних правилах, чем без связи вовсе.
func (s *Sluzhba) smenitYadroPlavno(ctx context.Context, p yadro.Peredacha) {
	log.Printf("ядро прошлой копии живо (pid %d), но конфиг сменился — поднимаю новое рядом, старое пока работает", p.PID)
	if err := s.PodnyatZashchitu(ctx); err != nil {
		log.Printf("новое ядро не поднялось (%v) — оставляю работать прежнее, связь не рву", err)
		return
	}
	log.Printf("новое ядро работает — гашу прежнее (pid %d)", p.PID)
	yadro.PogasitChuzhoe(p.PID)
}
