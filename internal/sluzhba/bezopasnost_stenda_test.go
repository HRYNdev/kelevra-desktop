// Ни одна проверка этого пакета не имеет права трогать настройки сети машины,
// на которой её гоняют.
//
// Замер 31.08. Обычная приёмка проекта гоняет тесты на линуксе, где весь
// windows-путь подменён заглушками (internal/proksi/proksi_other.go: Postavit
// и Snyat не делают ничего). Собранные же под Windows и запущенные на
// НАСТОЯЩЕЙ Windows — а не под wine, как стенд, — те же самые тесты доходят до
// живого proksi.Postavit: любой тест, доводящий PodnyatZashchitu до успеха в
// режиме браузеров, прописывает машине системный прокси 127.0.0.1:2412, за
// которым в этот момент никого нет. У человека от этого пропадают сайты — ровно
// та авария, которую всё это приложение и чинит.
//
// KELEVRA_PROKSI=net (см. internal/proksi: tolkoSmotrim) гасит запись
// начисто, оставляя чтение. Ставим его в TestMain, а не в стенде stend(t):
// часть проверок собирает Sluzhba руками, мимо стенда, и защита обязана
// накрывать весь пакет разом, а не тех, кто не забыл её позвать.
func TestMain(m *testing.M) {
	if err := os.Setenv("KELEVRA_PROKSI", "net"); err != nil {
		panic(err)
	}
	os.Exit(m.Run())
}
