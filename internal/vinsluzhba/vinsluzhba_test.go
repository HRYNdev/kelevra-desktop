package vinsluzhba

import (
	"strings"
	"testing"
)


// Имя службы попадает в реестр и в диспетчер служб, аргумент — в командную
// строку, которую система подставляет сама. Обе величины меняться не должны:
// после переименования установленная служба перестаёт находиться, а старая
// остаётся висеть навсегда. Тест стережёт их дословно.
func TestImenaNeMenyayutsya(t *testing.T) {
	if Imya != "KelevraSluzhba" {
		t.Fatalf("имя службы стало %q: установленная у людей служба перестанет находиться", Imya)
	}
	if Argument != "--vinsluzhba" {
		t.Fatalf("аргумент службы стал %q: система будет запускать её не в том режиме", Argument)
	}
}

// Имя службы без пробелов и кавычек: оно уходит в командную строку системы,
// и пробел в нём превратил бы одну службу в две несуществующие.
func TestImyaBezProbelov(t *testing.T) {
	if strings.ContainsAny(Imya, " \t\"'") {
		t.Fatalf("в имени службы %q есть пробел или кавычка", Imya)
	}
}

// Описание человек читает в списке служб Windows. Пустое описание там
// выглядит как чужая программа неизвестного назначения.
func TestOpisanieEst(t *testing.T) {
	if strings.TrimSpace(Opisanie) == "" {
		t.Fatal("описание службы пустое: в списке служб она будет безымянной")
	}
}
