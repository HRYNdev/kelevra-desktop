// Пакет vinsluzhba: работа Kelevra службой Windows.
//
// Зачем. Туннель поднимает не приложение, а ядро, и адаптеру нужны права
// администратора. Пока рабочий процесс живёт в сеансе человека, эти права
// приходится просить при каждом входе в систему: запись автозапуска лежит в
// пользовательской ветке реестра и повышения не даёт. Служба Windows решает
// это иначе — она стартует под системной учётной записью до входа в систему,
// и подтверждение спрашивается ровно один раз, когда службу ставят.
//
// Что сюда НЕ переезжает, и это не мелочь:
//   - системный прокси и запись автозапуска живут в ветке реестра ПОЛЬЗОВАТЕЛЯ
//     (internal/proksi, internal/avtozapusk); из-под системной учётной записи
//     они попали бы в чужой профиль и не сработали;
//   - окно и значок в трее требуют интерактивного сеанса, из службы их не
//     показать вовсе.
// Поэтому служба берёт на себя ядро, туннель и авторежим, а всё, что видно
// глазами или лежит в профиле человека, остаётся в оконной части.
package vinsluzhba

// Imya — имя службы в диспетчере служб Windows. Меняться не должно: по нему
// её находят установка, удаление и проверка состояния.
const Imya = "KelevraSluzhba"

// Opisanie — то, что человек прочитает в списке служб, если туда заглянет.
const Opisanie = "Kelevra: туннель и авторежим. Работает без входа в систему."

// Argument — с ним Kelevra.exe запускается как служба. Диспетчер служб
// подставляет его сам, руками этот режим не запускают.
const Argument = "--vinsluzhba"
