package obnovlenie

import "golang.org/x/sys/windows"

// spryatatFayl вешает на файл атрибуты «скрытый» и «системный».
//
// Зачем. Замена .exe на месте требует отодвинуть работающий файл в <имя>.old
// (Windows не даёт затереть запущенный .exe, но даёт его переименовать), и до
// 02.09 этот хвост просто ложился рядом с приложением на видное место — в ту
// самую папку, куда человек скачал Kelevra.exe и куда он смотрит. Жалоба
// 02.09 начинается ровно с него: «появляется .old, и всё» — файл на виду был
// единственным зримым следом обновления, и выглядел он как мусор после
// поломки, а не как страховка.
//
// Насовсем убрать хвост в момент замены нельзя: пока старая копия работает,
// он ЗАПУЩЕННЫЙ файл, и он же — то, чем bedaSOtkatom возвращает приложение в
// рабочее состояние, если новая сборка не встанет (железное обещание
// Postavit). Поэтому хвост живёт, но не на виду, и живёт недолго: новая копия
// стирает его сразу, как только смерть старой подтверждена (cmd/kelevra/main.go).
//
// HIDDEN и SYSTEM вместе, а не один HIDDEN: Проводник по умолчанию прячет
// системные файлы даже при включённом «показывать скрытые», и хвост не мозолит
// глаза даже тому, кто эту галку когда-то поставил.
//
// Отказ не беда и наверх не поднимается: не спрятали — значит человек увидит
// лишний файл на несколько секунд, а рушить из-за этого удавшуюся установку
// нельзя.
func spryatatFayl(put string) error {
	imya, err := windows.UTF16PtrFromString(put)
	if err != nil {
		return err
	}
	return windows.SetFileAttributes(imya, windows.FILE_ATTRIBUTE_HIDDEN|windows.FILE_ATTRIBUTE_SYSTEM)
}
