package kopiya

// Zamok — единая точка «я первый»: атомарный на уровне ОС взаимный
// исключитель, которым решается вопрос «поднимать свою службу или ждать
// чужую» — ДО любого чтения метки zapushcheno.json.
//
// Беда 23.08: Диспетчер задач показывал по несколько Kelevra.exe сразу
// («(3)», «(9)»), и ошибку при отключении, когда открыты 2 приложения.
// Причина — Nayti() и Zanyat() не атомарны между собой: между стартом
// службы и записью метки есть окно, и если .exe запускают второй раз
// быстро (до того как первая служба успела подняться и отметиться), второй
// процесс тоже не находит первую копию через Nayti() и тоже поднимает своё
// ядро. Метка на диске остаётся источником правды о ТОМ, ГДЕ живёт копия
// (адрес, PID, время) — Zamok решает только «кто первый» в момент старта и
// закрывает именно это временное окно, а не заменяет метку.
const imyaZamka = "Kelevra-Desktop-Zapusk-9f1c9b2c"

// Vzyat реализован отдельно на каждой платформе с одной и той же
// сигнатурой (zamok_windows.go — именованный мьютекс ОС, единственный
// настоящий атомарный примитив на Windows; zamok_other.go — файловый
// flock для сборки и тестов вне Windows, где продукт не живёт):
//
//	func Vzyat(timeout time.Duration) (*Zamok, bool)
//
// Ждёт до timeout, если замок уже занят другим процессом (тот поднимает
// свою службу). Возвращает (nil, false), если время вышло или сам
// примитив недоступен, — вызывающий действует так, будто замка нет
// (см. cmd/kelevra/main.go: деградация к прежнему поведению, а не отказ
// приложения целиком из-за замка).

// Zamok — держатель взятого замка.
type Zamok struct{ zakryt func() }

// Otdat освобождает замок. Безопасно звать на nil-получателе (замок не
// был взят — Vzyat вернул false) и повторно (второй вызов ничего не
// делает): вызывающему не нужно помнить, удалось ли взять замок, чтобы
// поставить defer.
func (z *Zamok) Otdat() {
	if z == nil || z.zakryt == nil {
		return
	}
	zakryt := z.zakryt
	z.zakryt = nil
	zakryt()
}
