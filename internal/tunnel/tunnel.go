// Пакет tunnel: след поднятого туннеля на диске и уборка за копией, которая
// умерла жёстко.
//
// Зачем он нужен, если Windows и так убирает за собой. Разбор ядра
// (sing-box 1.14 + sing-tun 0.8.12, сборка .github/workflows/core.yml) даёт
// три факта, и все три говорят, что туннель на Windows аварию переживает
// ЛУЧШЕ системного прокси:
//
//  1. Адаптер. Ядро несёт wintun внутри себя (sing-tun/internal/wintun +
//     memmod: DLL распакована в память, отдельного wintun.dll рядом с
//     sing-box.exe класть не надо — проверено по строкам самого бинаря).
//     Адаптер wintun принадлежит создавшему его процессу и уничтожается
//     драйвером, когда процесс уходит, — в том числе когда его убивают.
//  2. Маршруты. auto_route прописывает их на LUID адаптера. Нет адаптера —
//     нет и маршрутов, снимать отдельно нечего.
//  3. Правила фаервола (strict_route). Тут разбор дальше догадки не идёт, и
//     врать об этом нельзя. В бинаре ядра лежат И FwpmEngineOpen0 /
//     FwpmSubLayerAdd0 / FwpmFilterAdd0, И целый набор Delete* (замер 31.08
//     по самому sing-box.exe с машины человека: FwpmFilterDeleteByKey0,
//     FwpmSubLayerDeleteByKey0, FwpmProviderDeleteByKey0). Символы приезжают
//     из нескольких пакетов сразу (sing-tun и wireguard-windows), и по
//     одному их наличию нельзя сказать ни что сессия WFP динамическая, ни
//     что она статическая. Значит про фаервол мы НЕ знаем, переживёт ли
//     что-нибудь жёсткую смерть процесса.
//
// Из этого и растёт след на диске. Он не украшение к уверенному выводу — он
// ЕДИНСТВЕННОЕ, что у нас есть вместо уверенности: следующий запуск читает
// след и проверяет приборно, жив ли ещё адаптер с таким именем. Жив — вывод
// (1) неверен, и человеку об этом говорят вслух, а не молчат. Адаптера нет —
// нет и маршрутов на его LUID, потому что Windows снимает их вместе с
// интерфейсом, и остаться могли бы только правила WFP, которые без адаптера
// ничего не заворачивают.
//
// Отдельно про аварию 31.08 (системный прокси остался висеть на мёртвом
// порту, у человека пропал интернет): в туннельном режиме её источника нет
// вовсе — реестр не трогается, потому что системный прокси в этом режиме не
// ставится и вход mixed из конфига выброшен (internal/konfig). Больше того,
// подъём туннеля обязан снять прокси, оставшийся от прошлого прокси-режима:
// иначе браузеры пойдут на порт 2412, которого в туннельном конфиге уже нет
// (см. sluzhba.PodnyatZashchitu).
package tunnel

import (
	"encoding/json"
	"net"
	"os"
	"path/filepath"
	"strings"

	"github.com/HRYNdev/kelevra-desktop/internal/hranenie"
)

// imyaMetki — файл-след «мы подняли туннель». Живёт рядом с proksi.json
// (internal/proksi) и по той же причине: штатный выход снимает след сам, а
// жёсткую смерть процесса — Диспетчер задач, выключение питания, оконная
// сборка без консоли, не получающая SIGTERM — не переживёт ни один defer.
const imyaMetki = "tunnel.json"

func putMetki() string { return filepath.Join(hranenie.Papka(), imyaMetki) }

type metka struct {
	Adapter string `json:"adapter"`
	PID     int    `json:"pid"`
}

// Otmetit запоминает, что туннель подняли мы, и на каком адаптере. Ошибка
// записи не должна мешать защите: след — подстраховка, а не сама защита.
func Otmetit(adapter string, pid int) {
	b, err := json.Marshal(metka{Adapter: adapter, PID: pid})
	if err != nil {
		return
	}
	if err := os.MkdirAll(hranenie.Papka(), 0o755); err != nil {
		return
	}
	_ = os.WriteFile(putMetki(), b, 0o600)
}

// ProchestMetku — след прошлого (возможно, уже мёртвого) запуска.
func ProchestMetku() (adapter string, pid int, est bool) {
	b, err := os.ReadFile(putMetki())
	if err != nil {
		return "", 0, false
	}
	var m metka
	if err := json.Unmarshal(b, &m); err != nil {
		return "", 0, false
	}
	return m.Adapter, m.PID, true
}

// UbratMetku снимает след. Зовётся на каждом штатном опускании защиты и на
// выходе из приложения — после остановки ядра следу взяться неоткуда.
func UbratMetku() { _ = os.Remove(putMetki()) }

// Adapter — как приложение узнаёт, что адаптер туннеля ещё жив. Отдельным
// типом, а не прямым вызовом net.Interfaces() из логики уборки: проверку
// надо уметь подменить в тесте, а настоящих сетевых адаптеров в тесте быть
// не должно (см. запрет трогать сеть на машине человека).
type Adapter func(imya string) bool

// Zhivoy — боевая проверка: есть ли среди сетевых интерфейсов машины
// интерфейс с таким именем. Только чтение, ничего не меняет.
//
// Сравнение нестрогое по регистру и с обрезкой пробелов: имя адаптера
// приходит из профиля (interface_name), а Windows показывает его как есть,
// и разойтись эти две строки могут на пустом месте.
func Zhivoy(imya string) bool {
	if imya == "" {
		return false
	}
	spisok, err := net.Interfaces()
	if err != nil {
		// Не смогли посмотреть — честнее сказать «не вижу», чем выдумать
		// «висит»: ложная тревога заставит человека чинить несломанное.
		return false
	}
	for _, i := range spisok {
		if strings.EqualFold(strings.TrimSpace(i.Name), strings.TrimSpace(imya)) {
			return true
		}
	}
	return false
}

// Itog — что нашла уборка после жёсткой смерти прошлой копии.
type Itog struct {
	// BylSled — след туннеля на диске был, то есть прошлая копия ушла НЕ
	// штатно (штатный выход снимает след сам).
	BylSled bool
	// Adapter — имя адаптера из следа.
	Adapter string
	// AdapterVisit — адаптер ПЕРЕЖИЛ смерть процесса. Разбор говорит, что
	// так быть не должно (см. шапку файла); если это всё-таки случилось,
	// вывод разбора неверен и человеку об этом надо сказать, а не молчать.
	AdapterVisit bool
}

// UbratOsirotevshiy — уборка следа туннеля на старте новой копии.
//
// kopiyaZhiva — на машине уже работает другая копия приложения. Тогда след
// не наш и не осиротевший: чужая живая копия прямо сейчас держит туннель, и
// трогать её след — то же самое, что окну снимать прокси у живой службы
// (беда 20.08, см. cmd/kelevra/main.go).
//
// Сам след снимается ВСЕГДА, когда прошлая копия мертва, — даже если адаптер
// ещё виден. След описывает не систему, а намерение прошлой копии, и хранить
// его дальше значит копить ложную тревогу на каждом следующем запуске. То,
// что адаптер пережил процесс, возвращается вызывающему отдельным полем:
// это не повод молчать, это повод сказать.
func UbratOsirotevshiy(kopiyaZhiva bool, zhiv Adapter) Itog {
	adapter, _, est := ProchestMetku()
	if !est {
		return Itog{}
	}
	if kopiyaZhiva {
		return Itog{}
	}
	if zhiv == nil {
		zhiv = Zhivoy
	}
	visit := zhiv(adapter)
	UbratMetku()
	return Itog{BylSled: true, Adapter: adapter, AdapterVisit: visit}
}
