package yadro

import (
	"os"
	"path/filepath"
	"sort"
)

// NashiYadra — номера живых процессов, чей образ ОС подтверждает файлом bin.
//
// Зачем. Записка называет ядро номером процесса, а номер может разойтись с
// правдой: записку переписали, номер переиспользован, копия упала между
// запуском ядра и записью. Тогда по записке ядро не опознать, хотя оно живо и
// держит туннель — на машине остаётся сирота: связь работает, а выключить её
// из приложения нельзя, и следующее «Подключиться» поднимает второе ядро рядом.
//
// Ищем не по имени и не по строке пути, а по самому файлу образа
// (odinItotZhe: os.SameFile), тем же доводом, что и опознание по записке:
// посторонний процесс с тем же именем файла, но из другой папки, сюда не
// попадёт. Имя служит только грубым первым фильтром, чтобы не спрашивать ОС
// про каждый процесс в системе.
//
// Свой процесс не возвращается никогда: гасить себя вызывающему незачем.
func NashiYadra(bin string) []int {
	if bin == "" {
		return nil
	}
	if _, err := os.Stat(bin); err != nil {
		return nil
	}
	svoy := os.Getpid()
	var nashi []int
	for _, pid := range pidyPoImeni(filepath.Base(bin)) {
		if pid <= 0 || pid == svoy {
			continue
		}
		if ObrazNash(pid, bin) {
			nashi = append(nashi, pid)
		}
	}
	sort.Ints(nashi)
	return nashi
}
