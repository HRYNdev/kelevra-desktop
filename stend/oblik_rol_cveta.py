#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Стенд: РОЛЬ цвета, а не его значение.

Зачем он появился (29.08.2026). хозяин написал про окно: «есть эталон на
телефоне и там если что тоже оливковое наполнение а не бирюза». Он был прав:
состояние «защита работает» на компьютере красилось токеном --norma (#4fbfa4,
бирюза), тогда как на телефоне тот же индикатор давно оливковый —
Components.kt:73-79, его собственный комментарий: «Выбор хозяина 25.08.2026 после
примерки на живом телефоне: подключённое кольцо идёт В ТОН акценту, а не
отдельной ролью "норма". Бирюза рядом с оливой читалась как второй акцент»
(коммит 33fd5af в kelevra-box убрал там ветку colors.Ok).

Почему это не поймал старый сторож. Навык palitra_kanon сверяет ЗНАЧЕНИЯ
токенов: --norma == KDark.Ok == #4fbfa4 — совпадает байт в байт, значит
зелёный. И до правки, и после он одинаково зелёный, потому что к вопросу
«какой токен положен ЭТОМУ месту» он слеп вовсе. Сверка палитры не заменяет
сверки ролей.

Что судит этот стенд (по исходнику окна, без запуска):
  1. Ни одно правило состояния «работает» не красится --norma и не несёт
     бирюзовую rgba(79,191,164,...). Главный индикатор идёт акцентом.
  2. --norma в файле ещё жив: он не отменён, а сужен до технических пробников
     (скорость узла), как K.Ok на телефоне. Если он исчезнет совсем — это
     тоже расхождение с каноном, и стенд скажет об этом.

Запуск:  python3 stend/oblik_rol_cveta.py     (rc=0 зелёный, rc=1 красный)
"""
import re
import sys
from pathlib import Path

KOREN = Path(__file__).resolve().parent.parent
OBLIK = KOREN / "internal" / "sluzhba" / "oblik" / "index.html"

BIRYUZA_RGBA = re.compile(r"rgba\(\s*79\s*,\s*191\s*,\s*164")
NORMA = re.compile(r"var\(--norma\)")


def main() -> int:
    tekst = OBLIK.read_text(encoding="utf-8")
    bedy: list[str] = []

    # 1. Правила состояния «работает» — построчно, чтобы в отчёте был номер.
    for nomer, stroka in enumerate(tekst.splitlines(), start=1):
        golaya = stroka.split("/*")[0]
        if ".rabotaet" not in golaya:
            continue
        if NORMA.search(golaya) or BIRYUZA_RGBA.search(golaya):
            bedy.append(
                f"  🔴 {OBLIK.name}:{nomer} — состояние «работает» красится бирюзой,"
                f" а на телефоне это акцент (Components.kt:77 DialState.On -> colors.Accent)\n"
                f"      {golaya.strip()}"
            )

    # 2. --norma не должен пропасть вовсе: у него осталась своя роль.
    if not NORMA.search(tekst):
        bedy.append(
            "  🔴 токен --norma не используется НИГДЕ — на телефоне K.Ok жив"
            " (точка онлайна пира, пробники связи). Роль не отменяли, только сузили."
        )

    if bedy:
        print("Роль цвета разошлась с каноном телефона:")
        print("\n".join(bedy))
        return 1

    print("🟢 «работает» = акцент (олива), бирюза --norma осталась только")
    print("   под техническими пробниками — как K.Ok на телефоне.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
